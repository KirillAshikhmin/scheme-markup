// Изображения объектов на развёртке: свет.
//
// Двенадцать типов света стартового справочника делят одну форму
// `circle-cross` и получают одно изображение светильника. Бра от точечного на
// развёртке не отличить — ровно настолько, насколько их не отличить и на
// плане: форма у них общая, категорийная, и заказчик согласился на этот повтор
// сознательно. День, когда это станет мешать, лечится своей формой у бра (она
// же поможет плану), а не вторым ключом у изображения.
import { viewArc, viewCircle, viewLine, viewParts, viewRect } from "./kit.js";

export const VIEWS_LIGHT = {
  // Светильник: купол с лучами.
  lamp: {
    shapes: ["circle-cross", "circle", "circle-dot", "circle-rays"],
    mm: { width: 90, height: 90 },
    parts: viewParts(
      viewArc(0, 0.06, 0.3, Math.PI, 0, true),
      viewLine(-0.34, 0.06, 0.34, 0.06),
      [[-0.42, 0.3], [0, 0.42], [0.42, 0.3]].map(([x, y]) => viewLine(x * 0.6, y * 0.55, x, y)),
    ),
  },
  // ——— люстра (таск 216, G323) ———
  //
  // Слова заказчика: «И люстру сделай более красивой всё-таки, а то просто
  // шайба». Люстре нужно **своё** изображение, а не форма знака: имя
  // изображения — ключ её тела в объёме (таск 155), и пока ЛЮ приходила к
  // `lamp`, она и в кадре была плафоном.
  //
  // **Знака у неё здесь нет** (`shapes: []`), и это решение с ценой. Знак
  // просился один — «Круг с подвесом» (`circle-rays`), он и назван подвесом, —
  // но его уже носит мастер-выключатель заказчика, и переезд знака сменил бы
  // тому и рисунок на развёртке, и тело в объёме (G68). Поэтому люстра
  // приходит к своему изображению **именем у типа** (`view` в стартовом
  // справочнике) — верхней ступенью той же лестницы ADR 005.
  //
  // Следствие названо вслух: у **уже размеченного** объекта тип «Люстра» имени
  // не получит — справочник копируется при создании и дальше живёт сам
  // (так же в нём нет ночника, сушилки и слаботочного щита, попавших в шаблон
  // позже). Новый объект люстру получает сразу.
  //
  // Рисунок: потолочная чашка и четыре подвеса разной длины с огоньками на
  // концах — то же, из чего собрано тело.
  chandelier: {
    shapes: [],
    mm: { width: 500, height: 400 },
    parts: viewParts(
      viewLine(-0.3, -0.42, 0.3, -0.42),
      viewLine(0, -0.42, 0, -0.3),
      [
        [-0.3, 0.32],
        [-0.1, 0.1],
        [0.1, 0.24],
        [0.3, -0.02],
      ].map(([x, y]) => viewLine(x, -0.3, x, y)),
      [
        [-0.3, 0.32],
        [-0.1, 0.1],
        [0.1, 0.24],
        [0.3, -0.02],
      ].map(([x, y]) => viewCircle(x, y + 0.06, 0.06)),
      viewLine(-0.3, -0.3, 0.3, -0.3),
    ),
  },
  // Подсветка зеркала — **круглое зеркало** (таск 177, G262). Слова заказчика:
  // «Метку Подсветка зеркала отрисовывай как зеркало, круглое».
  //
  // Знак «кольцо» (`circle-ring`) переехал сюда от светильника, и это не
  // мелочь: по лестнице ADR 005 имя изображения старше формы, а формы у
  // заказчика в объекте **проставлены**, имён — нет. Поэтому зеркало приходит и
  // в уже размеченный чертёж, а не только в новый. Светильник кольца не
  // потерял: у него осталось четыре формы, и кольцо из них было самым
  // непохожим на плафон.
  //
  // Что рисуется: рама, стекло и четыре штриха подсветки по контуру — она и
  // есть предмет метки, и без неё зеркало на развёртке стало бы просто кругом.
  mirror: {
    shapes: ["circle-ring"],
    mm: { width: 600, height: 600 },
    parts: viewParts(
      viewCircle(0, 0, 0.46),
      viewCircle(0, 0, 0.36),
      [0.25, 0.75, 1.25, 1.75].map((turn) =>
        viewLine(
          Math.cos(turn * Math.PI) * 0.46,
          Math.sin(turn * Math.PI) * 0.46,
          Math.cos(turn * Math.PI) * 0.5,
          Math.sin(turn * Math.PI) * 0.5,
        ),
      ),
    ),
  },
  // Ночник: тот же купол, но присевший к полу, и свет вниз.
  nightLight: {
    shapes: [],
    mm: { width: 80, height: 80 },
    parts: viewParts(
      viewRect(-0.34, -0.3, 0.68, 0.4, 0.1),
      [-0.18, 0, 0.18].map((x) => viewLine(x, 0.14, x, 0.36)),
    ),
  },
  // Лента вертикальная: полоса во всю высоту ниши — её и ставят по высоте.
  //
  // Знак у неё один — «вертикальный прямоугольник». Второй, с засечками, ушёл
  // к полотенцесушителю (таск 186): засечки поперёк корпуса в этой палитре
  // значат решётку, а не полосу света, и лестница перекладин — его рисунок, а
  // не ленты. Ни одного типа с этим знаком нет ни в стартовом справочнике, ни
  // в объекте заказчика, поэтому переезд ничего не перерисовал (G68).
  stripVertical: {
    shapes: ["rect-vertical"],
    mm: { width: 40, height: 600 },
    parts: viewParts(
      viewRect(-0.5, -0.5, 1, 1, 0.3),
      [0, 1, 2, 3].map((index) => viewLine(-0.18, -0.32 + index * 0.21, 0.18, -0.32 + index * 0.21)),
    ),
  },
};
