// Кирпичи, из которых сложены **изображения объектов** на развёртке
// (таск 135, переписаны данными в таске 139, требование G198).
//
// Заказчик поправил слово: это не значки, а упрощённые изображения самих
// вещей. «Значок» уводит мысль к условному обозначению — оно живёт на плане и
// остаётся там неизменным.
//
// ——— почему описание, а не рисование ———
//
// Раньше изображение было функцией `draw(ctx, box)`: умело нарисоваться, но не
// умело сказать, из чего состоит. Для будущего объёмного вида этого мало —
// выдавить контур на глубину можно только зная контур.
//
// Теперь изображение — **список записей**: прямоугольник, окружность, линия,
// дуга, ломаная. Больше видов нет и не будет: заказчик сказал «очень
// примитивно», и это разрешение, а не ограничение. Не хватает примитива —
// **упрощается изображение**, а не растёт набор; иначе второй интерпретатор
// (объём) будет разбирать тот же зоопарк, что и первый.
//
// Доли — своего прямоугольника: −0.5…0.5 по обеим осям. Радиусы меряются по
// короткой стороне, поэтому круг остаётся кругом на любом прямоугольнике.
//
// Кирпичи ниже **возвращают записи**, а не рисуют. Рисует их один проход в
// `registry.drawObjectView`.

/** Прямоугольник со скруглением. `radius` 0 — обычный. */
export function viewRect(x, y, width, height, radius = 0) {
  return { kind: "rect", x, y, width, height, radius };
}

/** Плашка прибора во весь прямоугольник изображения. */
export function viewPlate(inset = 0.04, radius = 0.1) {
  return viewRect(-0.5 + inset, -0.5 + inset, 1 - inset * 2, 1 - inset * 2, radius);
}

export function viewCircle(cx, cy, r) {
  return { kind: "circle", cx, cy, r };
}

export function viewLine(x1, y1, x2, y2) {
  return { kind: "line", x1, y1, x2, y2 };
}

/** Дуга: купол светильника, обзор датчика, складка шторы. */
export function viewArc(cx, cy, r, from, to, close = false) {
  return { kind: "arc", cx, cy, r, from, to, close };
}

/** Ломаная: зонт вытяжки, объектив камеры, капля. */
export function viewPoly(points, close = false) {
  return { kind: "poly", points, close };
}

/** Решётка: ею читаются кондиционер, бризер и вытяжка — у всех троих она лицо. */
export function viewLouvers(count, from, to, left, right) {
  const parts = [];
  for (let index = 0; index < count; index += 1) {
    const y = from + ((to - from) * (index + 0.5)) / count;
    parts.push(viewLine(left, y, right, y));
  }
  return parts;
}

/** Дуги сигнала: присутствие, движение, WiFi. */
export function viewWaves(cx, cy, radii, from, to) {
  return radii.map((r) => viewArc(cx, cy, r, from, to, false));
}

/**
 * Капля: протечка, осушитель, водорозетка.
 *
 * Прямыми, а не кривой Безье, — и это **сознательное упрощение** (G198).
 * Кривая была единственным местом во всех тридцати двух изображениях, где
 * примитивов не хватало; объём по ней пришлось бы считать отдельным правилом.
 * Шесть отрезков читаются каплей ничуть не хуже — в размере, в котором их
 * видят на развёртке, разницы не видно вовсе.
 */
export function viewDrop(cx, cy, size) {
  const at = (dx, dy) => [cx + dx * size, cy + dy * size];
  return viewPoly(
    [at(0, -1), at(0.62, 0.15), at(0.45, 0.72), at(0, 0.92), at(-0.45, 0.72), at(-0.62, 0.15)],
    true,
  );
}

/** Плашка с клавишами: столько, сколько каналов у выключателя. */
export function viewKeys(count) {
  const parts = [viewPlate()];
  const width = 0.62 / count;
  for (let index = 0; index < count; index += 1) {
    parts.push(viewRect(-0.31 + index * width, -0.26, width * 0.84, 0.52, 0.04));
  }
  return parts;
}

/**
 * Собрать описание: кирпичи возвращают кто запись, кто список, и сложить их
 * в один плоский список — дело одного места, а не каждого изображения.
 */
export function viewParts(...items) {
  return items.flat(Infinity).filter(Boolean);
}
