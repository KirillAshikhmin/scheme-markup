// (таск 154, требование G224).
//
// Имя записи — ключ встроенного каталога (`objectCatalog.js`), он же ключ
// модели (`objectModels/objects.js`): три реестра сходятся на одном слове, и
// «добавить вещь» — это запись в каталоге, рисунок здесь и тело там.
//
// ——— вид сверху, а где он ничего не говорит — с лица ———
//
// Вещь на чертеже видна сверху, и рисунки здесь плановые: у кровати подушки, у
// плиты конфорки, у лестницы ступени со стрелкой подъёма — так их и чертят.
// Но у вещи **на стене** вид сверху — одна полоса: картина, полотенцесушитель,
// радиатор и щит сверху неразличимы между собой и от любого другого бруска.
// Их рисунок взят с лица, и это сознательное исключение: плитка выбора обязана
// отвечать на вопрос «та ли это вещь», а полоса на него не отвечает никак.
//
// `shapes` у всех пустые: формы знаков — про метки, и вещь чертежа по форме
// знака не ищут. `mm` нет вовсе: размер вещи живёт в каталоге, и второго
// владельца у него быть не должно.
