// Габарит вещи в миллиметрах — один ответ на обе поверхности.
//
// Требование G226, таск 156. Слова заказчика: «Да, своди — с миграцией и
// тестом на старом объекте».
//
// ——— что здесь сведено ———————————————————————————————————————————————————
//
// Размеры у типа необязательны, и недостающую сторону приходится откуда-то
// брать. Правило на это было написано **дважды** и разошлось:
//
//   - развёртка (`elevationMarkBox`) подставляла габарит изображения объекта
//     **по каждой стороне отдельно**: нет ширины — берётся ширина изображения;
//   - объём (`volumeMarkPlacement`) брал запас (G215) только когда не задано
//     **ни одной** стороны, а при одной заданной тянул вторую до нижнего
//     предела видимости (`VOLUME_MARK_MIN_MM`, 20 мм).
//
// Вещь с длиной 600 и пустой шириной выходила 600 × 90 на развёртке и
// 600 × 20 в объёме. Это одна вещь, и человек смотрит на неё то там, то там.
//
// Поэтому правило живёт здесь одно, и обе поверхности **зовут** его, а не
// повторяют. Оставь два места — разойдётся снова.
//
// ——— само правило ————————————————————————————————————————————————————————
//
// Взято **развёрточное**, и выбор не произвольный: каждая сторона отвечает за
// себя. Изображение объекта — не картинка «вообще», а габарит настоящей вещи
// (розетка 80 × 80, кондиционер 900 × 300, вертикальная лента 40 × 600), и
// сторона, которой человек не назвал, честнее всего берётся у той же вещи.
// Прежний ответ объёма — «не сказано ни одной, значит запас; сказана одна,
// значит вторая по нижнему пределу» — смешивал два разных вопроса: «какая
// сторона у вещи» и «меньше чего её нельзя рисовать, чтобы в неё попали
// кликом».
//
// Изображения нет совсем — остаётся общая рамка **80 × 80 × 10 мм**. Она тоже
// не выдумана: ровно эти числа стоят в стартовом справочнике у выключателя «В»
// и розетки «Р» (`TEMPLATE_TYPES`), то есть это обычный подрозетник, которого
// в квартире больше всего.
//
// **Ноль на стороне лица — это пустота, а не ноль.** Вещи нулевой длины не
// бывает, и записанный ноль читается как «не сказано» — так развёртка и
// считала (`Number(size.width) || view.mm.width`). Выступ (`depth`) живёт по
// другому правилу, и оно остаётся за объёмом: там записанный ноль — это ноль
// («встроенный»), а не пустота.
//
// ——— почему при отрисовке, а не записью в справочник ——————————————————————
//
// Недостающую сторону можно было бы дописать типу при открытии, как
// `fillTypeSizes` (G192) дописывает размеры типам без них. Так не сделано:
//
//   - **числа были бы чужие.** Человек открыл карточку своего типа — и видит
//     там ширину 90, которой не вписывал. Умолчание шаблона (G192) он хотя бы
//     узнаёт по своему коду типа, а 90 здесь — размер картинки светильника;
//   - **догадка перестала бы следовать за изображением.** Записанное число
//     старше любого умолчания: поправь потом габарит изображения — и тип
//     останется с прежней догадкой;
//   - **G68.** Правка, после которой готовый объект открывается иначе, чем
//     закрывался, — испорченная работа. Подтяжка при отрисовке не пишет в
//     объект ни байта, и старый файл остаётся ровно собой.
//
// Поэтому «миграция» здесь значит, что старый файл открывается и ведёт себя
// предсказуемо, а не что в нём что-то переписано. Сказать о догадке словом
// обязанность остаётся: объём перечисляет такие вещи строкой под полем
// (`volumeMarks().spare`).

/**
 * Общая рамка: габарит вещи, о которой не известно ничего — ни размеров у
 * типа, ни изображения объекта. Числа из стартового справочника (выключатель
 * «В», розетка «Р»): обычный подрозетник.
 *
 * Выступ у плоского изображения взять негде — записи реестра двумерные, — и
 * рамка отвечает на него за всех, у кого своего выступа нет.
 */
export const MARK_BOX_FRAME_MM = 80;
export const MARK_BOX_FRAME_DEPTH_MM = 10;

// Сторона лица задана, если это положительное число: ноль и пустота здесь
// значат одно — «не сказано».
function markBoxOwn(value) {
  const number = Number(value);
  return Number.isFinite(number) && number > 0 ? number : null;
}

/**
 * Габарит лица вещи в миллиметрах из размеров и изображения объекта.
 *
 * `sizes` — `{lengthMm, widthMm}`: длина **вдоль** поверхности и вторая сторона
 * лица, как их понимает модель (`markSizes().length` и `.width`). `view` —
 * изображение объекта (`objectViews/registry.js`) или `null`, если его нет;
 * его `mm.width` отвечает за длину, `mm.height` — за вторую сторону.
 *
 * `lengthFrom` и `widthFrom` говорят, **откуда** взята каждая сторона:
 * `"own"` — записана человеком (у метки или у типа), `"view"` — габарит
 * изображения, `"frame"` — общая рамка. `guessed` — хоть одна сторона
 * догадана: по нему поверхность и решает, о чём сказать человеку.
 *
 * Нижние пределы отрисовки здесь не живут и жить не должны: `VOLUME_MARK_MIN_MM`
 * (меньше чего вещь не выделить кликом) и `ELEVATION_VIEW_MIN_PX` (меньше чего
 * вещь не узнать на листе) — ответы на другие вопросы и остаются у своих
 * поверхностей.
 *
 * Чистая и вынесена наружу: это то самое место, где легче всего соврать о
 * размере вещи, и проверяется оно без холста.
 */
export function markBoxMm(sizes, view) {
  const mm = view && view.mm ? view.mm : null;
  const side = (own, fromView) => {
    const mine = markBoxOwn(own);
    if (mine !== null) return { mm: mine, from: "own" };
    const image = markBoxOwn(fromView);
    if (image !== null) return { mm: image, from: "view" };
    return { mm: MARK_BOX_FRAME_MM, from: "frame" };
  };
  const length = side(sizes ? sizes.lengthMm : null, mm ? mm.width : null);
  const width = side(sizes ? sizes.widthMm : null, mm ? mm.height : null);
  return {
    lengthMm: length.mm,
    widthMm: width.mm,
    lengthFrom: length.from,
    widthFrom: width.from,
    guessed: length.from !== "own" || width.from !== "own",
    // Имя изображения, у которого взята хоть одна сторона: для разбора «откуда
    // у вещи этот габарит», а не для отрисовки.
    from: length.from === "view" || width.from === "view" ? view.name || null : null,
  };
}
