// Модели **вещей чертежа** — того, что расставляют в режиме «Чертёж».
//
// Ключи — ключи встроенного каталога (таск 154): тринадцать вещей из брифа
// заказчика (стол, кровать, бассейн, стиральная и сушильная машины, раковина,
// полотенцесушитель, душ, тумба, картина, плита, посудомойка, холодильник) и
// девять нынешних видов (колонна, ниша, короб-стояк, лестница, щит, радиатор,
// столешница, сантехника, шкаф) — шкаф у них общий, поэтому ключей двадцать
// два.
//
// ——— мост до каталога ———
//
// Каталог пишется параллельно, и пока его нет, у вида объекта есть только
// `name`, который человек правит руками. Поэтому у модели есть **слова** —
// корни, по которым имя вида узнаётся так же терпимо, как узнаёт лестницу
// объём (`volumeStairKind`): регистр, «ё» и пробелы по краям не считаются.
// Появится ключ — он старше имени, и мост перестанет работать сам собой,
// ничего не удаляя (`volumeObjectModel`).
//
// Сравнение по словам идёт **от самого длинного корня**, и это не украшение:
// «Столешница (кухонный фронт)» содержит и `столешниц`, и `стол`, а стол со
// столешницей — две разные вещи.
