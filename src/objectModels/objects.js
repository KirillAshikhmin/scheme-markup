const modelStair = (key, widthMm, depthMm) => objectStairModel(key, { widthMm, depthMm, heightMm: MODEL_STAIR_FLOOR_MM });

// Стиральная и сушильная машины — **одна модель**, и это честнее двух.
// Отличаются они надписью на панели, а телом — ничем: тот же корпус, тот же
// люк, те же габариты. Выдумывать им разные тела значило бы врать глазами.
// Колонна и короб-стояк — **одно описание**: и то и другое в объёме есть ствол
// во весь габарит, и силуэт у них один. Делить их двумя одинаковыми записями
// значило бы развести то, что завтра правится вместе.
