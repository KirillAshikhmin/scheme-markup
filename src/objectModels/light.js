// Модели меток: свет.
//
// **Одна модель на семь точечных типов света** — и это не экономия, а та же
// цена, что уже заплачена за плоские изображения (`objectViews/light.js`):
// типы света делят форму знака `circle-cross`, значит и изображение у них
// одно, значит и модель одна. Восьмой — подсветка зеркала — ушёл со своим
// знаком «кольцо» в таске 177: когда вещь нужно отличить **телом**, лечится это
// знаком, и ровно так же вылечилась она. Разводит их **габарит**, и
// разводит сильнее, чем могли бы разные описания: у точечного светильника
// 90 × 90 при нулевом выступе из одного и того же описания выходит плоская
// шайба в потолке, у люстры 500 × 400 × 300 — широкий плафон на подвесе, у бра
// 150 × 250 × 120 — чаша на стене. Описание в долях тем и сильно, что форма
// вещи берётся от её размеров.
//
// День, когда люстру понадобится отличить от точечного **телом**, лечится
// своей формой знака у люстры (она же поможет плану) — тем же путём, которым
// лечится их неразличимость на плане, а не вторым ключом у модели.
//
// ——— что светится (таск 09 сценариев, G06) ———
//
// `lit: true` стоит у тел, **откуда идёт свет**: абажур и ярус лампы, подвесы
// люстры, свечение ночника и зеркала, рассеиватель ленты. Признак значит «может
// светиться»: горит тело или нет и насколько ярко — решает состояние дома в
// кадре «Объёма», а не модель. Подставка, чашка, корпус и стекло не светятся.
import { modelBox, modelCone, modelCyl, modelParts, modelPlate, modelTube } from "./kit.js";

// ——— рожки и шарики висячей люстры (таск 260, G402) ————————————————————————
//
// Слова заказчика о висячей люстре таска 256: «Ну это не красивая люсьра
// получилась, и даже не понятно что это… вот сделай что-то в этом стиле,
// только где лампы-свечки пусть шарики будут». На фотографии образца — чашка у
// потолка, цепь, хрустальная колонна, от неё в стороны расходятся изогнутые
// рожки, на каждом лампа.
//
// **Рожки стоят по кругу, и держит это плита по контуру** (`modelPlate`).
// Коробка и цилиндр привязаны к осям габарита: четыре рожка по ±x и ±y — это
// крестовина, а не люстра, и пятого между ними не поставить вовсе. Плита же
// берёт свои вершины в долях, то есть любой угол, — и пять рожков через 72°
// описываются ею без единого нового вида тела. Это та же плита, которой
// собрана ступень винтовой лестницы, и заведена она была ровно за этим:
// «коробку повернуть нечем».
//
// **Рожок — клин, а не брусок.** Треугольник стоит пять граней, брусок шесть;
// на пяти рожках это пять граней, то есть половина шарика. И клин честнее: рожок
// на фотографии у ступицы толстый, а к подсвечнику сходит на нет.
//
// **Шарик — стоячий цилиндр высотой в свой поперечник.** Сферы в наборе нет
// нарочно (`objectModels/kit.js`: «у низкополигонально это не ограничение, а
// само задание»), и круглое здесь собирается тем же, чем собрано всё круглое в
// сборке. Восьмигранник ростом с диаметр читается шаром; ниже — шайбой, и это
// то же допущение, которым круглое зеркало стало кругом.
//
// Шестигранной плитой шарик стоил бы восемь граней вместо десяти, и пять
// шариков уложились бы в девяносто — это пробовалось живым прогоном и
// отвергнуто: снизу, то есть с того ракурса, с которого на люстру и смотрят,
// шесть сторон от восьми отличаются, а заказчик просил шарики. Десять граней
// на шарик — и есть та причина, по которой предел метки в гранях стал сотней
// (`OBJECT_MODEL_FACE_MAX`).
//
// **Кольцо рожков задано одной долей на обе оси, а шарик — двумя.** Кольцо
// повторяет пропорции габарита (у «ЛЮ» 500 × 400) и заполняет его целиком, как
// и положено люстре. Шарику же круглым надо быть **в миллиметрах**, а не в
// долях, и доля по глубине у него больше доли по ширине ровно в 500/400 —
// то же правило, по которому круглым остаётся зеркало подсветки.
//
// ——— вдвое крупнее габарита ———
//
// Слова заказчика на первые снимки этой люстры: «сделай её побольше, раза в 2».
// Габарит «ЛЮ» в стартовом справочнике — 500 × 400 × 300, и ни в одном из
// четырёх живых объектов его не правили: все люстры стоят на нём. Люстры такого
// размера не бывает — 300 мм это высота плафона, а не люстры с подвесом и
// рожками, — и описание вышло честным по долям и мелким на глаз.
//
// **Растёт рисунок, а не число человека** (G68). Габарит остаётся габаритом:
// по нему метка выделяется, меряется, пишется в колонку размеров и ложится
// знаком на план. Наружу выходит только тело — ровно так же, как выходит из
// габарита полотно шторы (`toFloor`) и круг зеркала подсветки (`round`).
// Разница одна и она в пользу этого способа: там признак читает интерпретатор,
// а здесь всё сказано **самими долями**, и второго механизма заводить не
// пришлось. Доля больше половины и значит «за габаритом» — система долей это
// выражает сама.
//
// **Вниз, а не во все стороны.** Верх габарита (доля 1) остаётся на месте:
// люстра висит под потолком, и расти ей некуда, кроме как вниз. Поэтому
// `chandelierGrown` тянет ширину и глубину от середины, а высоту — от верха:
// чашка остаётся у потолка, а нижний край уходит на вторую высоту габарита.
// У «ЛЮ» это 835 × 671 мм при свесе 576 мм — размер люстры, а не плафона.
//
// **Цена этого решения названа честно:** люстра, поставленная вплотную к
// стене, рисунком в стену и уйдёт. На живых объектах заказчика люстры стоят
// посреди помещений, и это проверено глазами; день, когда кто-то поставит её в
// угол, лечится габаритом самой метки, а не вторым правилом здесь.
//
// Описание при этом написано в **обычных долях**, −0.5…0.5: вдвое его
// увеличивает одна видимая строка, и читать запись по-прежнему можно, не держа
// множитель в уме.

/** Сколько рожков: пять — ни одной оси габарита, то есть кольцо, а не крест. */
const CHANDELIER_HORNS = 5;
/** Доля габарита: кольцо шариков, конец рожка и его ступица. */
const CHANDELIER_RING = 0.36;
const CHANDELIER_HORN_TIP = 0.33;
const CHANDELIER_HORN_HUB = 0.07;
/** Полупоперечник шарика по ширине габарита; с двойным ростом это 150 мм. */
const CHANDELIER_BALL = 0.075;
/** Во сколько доля по глубине длиннее доли по ширине у «ЛЮ»: 500 / 400. */
const CHANDELIER_DEEP = 1.25;

/** Во сколько раз рисунок крупнее габарита — см. «вдвое крупнее» выше. */
const CHANDELIER_GROW = 2;

/** Точка кольца: доли по ширине и по глубине на заданном угле. */
function chandelierAt(angle, radius) {
  return [Math.cos(angle) * radius, Math.sin(angle) * radius];
}

/**
 * Те же тела, растянутые из габарита: ширина и глубина — от середины, высота —
 * **от верха вниз**, потому что верх габарита стоит у потолка.
 */
function chandelierGrown(parts) {
  const grow = CHANDELIER_GROW;
  return parts.map((part) => ({
    ...part,
    x: part.x * grow,
    width: part.width * grow,
    y: part.y * grow,
    depth: part.depth * grow,
    z: 1 - (1 - part.z) * grow,
    height: part.height * grow,
    ...(part.points ? { points: part.points.map(([px, py]) => [px * grow, py * grow]) } : {}),
  }));
}

/**
 * Рожки с шариками: на каждый рожок клин от ступицы наружу и шарик на его
 * конце. Первый рожок смотрит на лицо габарита, дальше через 72°.
 */
function chandelierHornParts(hornZ, hornHeight, ballZ, ballHeight) {
  const parts = [];
  const step = (Math.PI * 2) / CHANDELIER_HORNS;
  // Полуугол клина у ступицы: много меньше половины шага, чтобы рожок читался
  // прутком, а не лопастью вентилятора — это найдено живым прогоном.
  const spread = step * 0.16;
  // Полупоперечник шарика по глубине: та же мерка в миллиметрах, что и по
  // ширине, — см. «кольцо одной долей, а шарик двумя» выше.
  const ballDeep = CHANDELIER_BALL * CHANDELIER_DEEP;
  for (let index = 0; index < CHANDELIER_HORNS; index += 1) {
    const angle = -Math.PI / 2 + index * step;
    const number = index + 1;
    parts.push(
      modelPlate(
        "horn" + number,
        [
          chandelierAt(angle - spread, CHANDELIER_HORN_HUB),
          chandelierAt(angle + spread, CHANDELIER_HORN_HUB),
          chandelierAt(angle, CHANDELIER_HORN_TIP),
        ],
        { z: hornZ, height: hornHeight, material: "light" },
      ),
    );
    const [atX, atY] = chandelierAt(angle, CHANDELIER_RING);
    parts.push(
      modelCyl("ball" + number, {
        x: atX - CHANDELIER_BALL,
        width: CHANDELIER_BALL * 2,
        y: atY - ballDeep,
        depth: ballDeep * 2,
        z: ballZ,
        height: ballHeight,
        material: "light",
        lit: true,
      }),
    );
  }
  return parts;
}

