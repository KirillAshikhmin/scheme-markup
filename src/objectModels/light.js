// Модели меток: свет.
//
// **Одна модель на восемь точечных типов света** — и это не экономия, а та же
// цена, что уже заплачена за плоские изображения (`objectViews/light.js`):
// двенадцать типов света делят форму знака `circle-cross`, значит и
// изображение у них одно, значит и модель одна. Разводит их **габарит**, и
// разводит сильнее, чем могли бы разные описания: у точечного светильника
// 90 × 90 при нулевом выступе из одного и того же описания выходит плоская
// шайба в потолке, у люстры 500 × 400 × 300 — широкий плафон на подвесе, у бра
// 150 × 250 × 120 — чаша на стене. Описание в долях тем и сильно, что форма
// вещи берётся от её размеров.
//
// День, когда люстру понадобится отличить от точечного **телом**, лечится
// своей формой знака у люстры (она же поможет плану) — тем же путём, которым
// лечится их неразличимость на плане, а не вторым ключом у модели.
import { modelBox, modelCyl, modelParts } from "./kit.js";

export const MODELS_LIGHT = {
  // Светильник: плафон двумя ярусами и тонкий подвес над ними.
  //
  // **Люстра «побольше и посимпатичнее»** (таск 177, G262) лечится здесь, а не
  // своим ключом: модель у точечных типов света одна, и разводит их габарит
  // (см. выше). Было так: плафон на три пятых габарита и толстый цилиндр
  // подвеса на остальные две — у люстры 500 × 400 × 300 это читалось шайбой с
  // трубой, то есть вещью **ниже** своего габарита. Стало: плафон во всю
  // ширину и три четверти высоты двумя ярусами, подвес — волосок в десятую
  // часть ширины. Люстра выросла и обрела ярус, точечный светильник (90 × 90
  // при нулевом выступе) остался той же плоской шайбой — у него на все ярусы
  // два миллиметра выступа, и делить их не на что.
  //
  // Цена — шесть граней: двадцать было, двадцать шесть стало. Это та же цена,
  // что у любой вещи с третьим телом, и предел в тридцать она не трогает.
  lamp: modelParts(
    modelCyl("shade", { z: 0, height: 0.52, material: "light" }),
    modelCyl("tier", { x: -0.28, width: 0.56, y: -0.28, depth: 0.56, z: 0.52, height: 0.22, material: "light" }),
    modelBox("rod", { x: -0.05, width: 0.1, y: -0.05, depth: 0.1, z: 0.74, height: 0.26, material: "metal" }),
  ),
  // Ночник: корпус у плинтуса и светящаяся щель внизу.
  nightLight: modelParts(
    modelBox("glow", { x: -0.34, width: 0.68, y: -0.5, depth: 0.35, z: 0.08, height: 0.26, material: "light" }),
    modelBox("case", { x: -0.42, width: 0.84, y: -0.15, depth: 0.65, z: 0.08, height: 0.7 }),
  ),
  // Лента вертикальная: профиль и рассеиватель во всю высоту.
  stripVertical: modelParts(
    modelBox("diffuser", { x: -0.34, width: 0.68, y: -0.5, depth: 0.3, material: "light" }),
    modelBox("profile", { y: -0.2, depth: 0.7 }),
  ),
};
