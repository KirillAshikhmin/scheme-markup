// Реестр **низкополигональных моделей** (таск 155, требование G221): один
// плоский справочник «ключ → список тел» и две лестницы, которыми модель
// находят.
//
// ——— откуда у метки модель ———
//
// **По имени её изображения, и третьего механизма не заводится.** Лестница у
// цвета, формы и изображения уже выстроена (ADR 005, `objectViews/registry.js`):
// имя у типа старше формы знака, форма — старше ничего. Модель садится на её
// последнюю ступень: нашлось изображение — его имя и есть ключ модели.
//
// Это даёт сразу три вещи. **Полный охват без единого нового поля:** у всех
// сорока девяти типов стартового справочника изображение есть (это держит
// `test/objectViews.test.js`), значит есть и модель. **Объект заказчика
// оживает без миграции:** в его 592 метках имён изображений нет ни одного, но
// форма знака проставлена, и модель находится по ней — ровно так же, как
// нашлось изображение (G68, объект не меняется). **Одна цена вместо двух:**
// двенадцать типов света делят форму `circle-cross`, и у них одно изображение
// и одна модель — цена, объявленная ещё в таске 135, второй раз не платится.
//
// ——— откуда у вещи чертежа модель ———
//
// По ключу встроенного каталога (таск 154), а у вещи прежней разметки ключа
// нет — там он выводится из имени вида, и переводит имя в ключ сам каталог
// (`objectCatalogKeyByName`), а не второй список слов здесь.
import { objectCatalogEntry, objectCatalogKeyByName } from "../objectCatalog.js";
import { MODELS_CLIMATE } from "./climate.js";
import { MODELS_LINES } from "./lines.js";
import { MODELS_LIGHT, MODELS_LIGHT_HANGING } from "./light.js";
import { MODELS_NET } from "./net.js";
import { MODELS_OBJECTS } from "./objects.js";
import { MODELS_KEYED, MODELS_POWER } from "./power.js";
import { MODELS_SENSE } from "./sense.js";
import { MODELS_THINGS } from "./things.js";
import { MODEL_CYL_SIDES } from "./kit.js";

/**
 * Предел тел **у модели метки** — пятнадцать (таск 260, G402). Слова
 * заказчика о висячей люстре: «Лимит на количество обектов подняли же до 15,
 * не надо 5… у меток тоже увеличь ограничение».
 *
 * **Было пять, и пять было посчитано честно:** тело коробкой стоит шесть
 * граней, цилиндром — десять, а меток на схеме сотни против единиц вещей
 * каталога. Это и сейчас так — изменилось другое. Рожковую люстру в пять тел
 * не собрать ни при каком старании: у неё кольцо ламп на рожках, а пять тел
 * хватает на чашку, цепь и три плиты, из которых люстры не выходит (таск 256 в
 * этом и провалился). Предел оказался не границей аккуратности, а запретом на
 * одну породу вещей.
 *
 * **Чем это оплачено.** Тяжёлая модель здесь **по выбору человека**: пятнадцать
 * тел взяла одна висячая люстра, и берёт она их только там, где отметку
 * поставили. Обычная люстра осталась в пяти телах, и остальные тридцать девять
 * моделей метки — тоже: предел это потолок, а не задание. Цену держит не он, а
 * средняя цена модели в гранях (`test/volumeModels.test.js`) и замер кадра
 * (`npm run bench`), и оба названы числами в тикете таска 260.
 *
 * На живых объектах заказчика люстр единицы: в самом большом (592 метки, 190
 * ламп) их **ноль** — лампы там точечные, а отметка «Висячая» предлагается
 * только изображению `chandelier`; в объекте, где их больше всего, их пять.
 * Поэтому подъём предела стоит сцене сотни граней из тысяч, а не кратного
 * роста.
 */
export const OBJECT_MODEL_BODY_MAX = 15;

/**
 * Предел граней у модели метки — сто, то есть **десять круглых тел**.
 *
 * Число тел и число граней меряют разное, и путать их нельзя: коробка стоит
 * шесть граней, цилиндр десять. Девяносто у вещи каталога — это «пятнадцать
 * коробок», и мерка честная: вещи каталога и есть коробки — шкаф, полки, борта
 * ванны. Люстра круглая: пять шариков и колонна — шесть цилиндров, шестьдесят
 * граней ещё до чашки с цепью. Мерить круглое коробками значит решать за вещь,
 * какой ей быть, — а именно в это и упёрся таск 256.
 *
 * Сто — верхняя честная оценка круглой модели: пятнадцать цилиндров стоили бы
 * полтораста, и столько не нужно никому. Запас мал нарочно: рожковая люстра
 * берёт 97, и следующему придётся либо уложиться, либо прийти с доводом —
 * ровно так же, как это устроено у потолка средней цены.
 */
export const OBJECT_MODEL_FACE_MAX = 100;

/**
 * Предел тел **у модели вещи каталога** — пятнадцать (G06, слова заказчика:
 * «подними лимит до 15»).
 *
 * **Почему предел разделён, а не поднят один на всех.** Он был один на метки и
 * вещи, потому что реестр плоский, — и подними его целиком, триста меток на
 * схеме получили бы лицензию на пятнадцать тел молча. А просил заказчик
 * другого: «у гардеробной одна полка» — вещь каталога, которой пяти тел
 * не хватает на то, из чего она состоит. Вещей на объекте единицы (в объекте
 * заказчика их шесть при 86 метках), меток — сотни, и цену кадра платит
 * поставленное, а не каталог. Поэтому предел читается **по ключу**:
 * каталожный ключ — пятнадцать тел, всё остальное — прежние пять.
 *
 * **С таска 260 тел у обоих поровну**, и разделение держится теперь на одних
 * гранях: у вещи-коробки их девяносто, у круглой метки сто. Дверь остаётся
 * одна — разойдись числа снова, менять придётся эти строки, а не искать по
 * сборке, кто ещё решает «вещь это или метка».
 *
 * Лестницы остаются своим исключением (`OBJECT_STAIR_KEYS`): их модель
 * собирается по габариту ступенями, и предел у неё считается в ступенях.
 *
 * Цена замерена `npm run bench` на сцене «квартира с мебелью», куда ради этого
 * замера поставлены гардеробная, обувница и вешалка (`tools/bench/scenes.mjs`):
 * граней 540 → 570, многоугольников в кадре 625 → 626, кадр JS 0,45 → 0,44 мс,
 * сборка света 10,5 → 10,5 мс. То есть выросшая гардеробная стоит сцене
 * тридцать граней, а кадру — ничего: пять полок стоят внутри её же габарита, и
 * дерево порядка (BSP) отдаёт в кадр те же многоугольники.
 */
export const OBJECT_MODEL_THING_BODY_MAX = 15;

/**
 * Предел граней у модели вещи: пятнадцать коробок. Не поднят вместе с меткой
 * (таск 260): у вещи каталога тела и есть коробки, и девяносто ей по мерке —
 * самая дорогая, гардеробная, стоит шестьдесят.
 */
export const OBJECT_MODEL_THING_FACE_MAX = 90;

/**
 * Предел тел и граней для одного ключа: у вещи встроенного каталога свой,
 * у метки прежний. Единственная дверь к этим числам — своего сравнения
 * «вещь это или метка» не заводить: ключ у них общий (телевизор, вытяжка и
 * полотенцесушитель — и вещь, и изображение метки сразу), и разойдись два
 * ответа, предел молча достался бы не тому.
 */
export function objectModelLimits(key) {
  return objectCatalogEntry(key)
    ? { bodies: OBJECT_MODEL_THING_BODY_MAX, faces: OBJECT_MODEL_THING_FACE_MAX }
    : { bodies: OBJECT_MODEL_BODY_MAX, faces: OBJECT_MODEL_FACE_MAX };
}

const MODEL_FAMILIES = [
  MODELS_POWER,
  MODELS_LIGHT,
  MODELS_CLIMATE,
  MODELS_SENSE,
  MODELS_NET,
  MODELS_THINGS,
  MODELS_OBJECTS,
];

const MODELS = {};
const CLASHES = [];
for (const family of MODEL_FAMILIES) {
  for (const [key, parts] of Object.entries(family)) {
    // Два семейства, занявшие один ключ, иначе молча затёрли бы друг друга —
    // и у половины типов модель оказалась бы чужой. Список пустой держит тест.
    if (MODELS[key]) CLASHES.push(key);
    MODELS[key] = { key, parts };
  }
}

/** Модель по ключу. `null` — такого ключа нет, и вещь рисуется габаритом. */
export function objectModelByKey(key) {
  return key && MODELS[key] ? MODELS[key] : null;
}

/** Все ключи — для сверки охвата и различимости силуэтов. */
export function objectModelKeys() {
  return Object.keys(MODELS).sort();
}

/** Ключи, занятые дважды. Пусто — иначе тест красный. */
export function objectModelClashes() {
  return [...CLASHES];
}

/**
 * Сколько граней стоит модель: коробка — шесть, цилиндр — своих сторон плюс
 * две. Лежачий цилиндр (таск 177) стоит ровно столько же, сколько стоячий:
 * бока и два днища, — поэтому новый вид тела предела не сдвинул.
 */
export function objectModelFaceCount(model) {
  let faces = 0;
  for (const part of (model && model.parts) || []) {
    if (part.kind === "plate") faces += part.points.length + 2;
    else faces += part.kind === "cyl" || part.kind === "tube" ? MODEL_CYL_SIDES + 2 : part.kind === "cone" ? MODEL_CYL_SIDES + 1 : 6;
  }
  return faces;
}

/**
 * Модель с клавишами **по числу каналов типа** (таск 177, G274).
 *
 * Клавишных моделей три с половиной — выключатель на одну, две, три клавиши и
 * переключатель, — а каналов у типа бывает и четыре: «ПП» из стартового
 * справочника двухканальный, а изображение у него переключателя с одной
 * клавишей, и до этого таска он так и стоял на стене одноклавишным. Поэтому
 * число клавиш берётся не из записи реестра, а у типа.
 *
 * Модель, у которой клавиш и так столько, сколько надо, отдаётся **той же
 * ссылкой**: общее описание остаётся общим, и тесты, сверяющие его по ссылке,
 * видят ровно то, что видели.
 *
 * Неклавишная модель проходит насквозь: каналы бывают и у реле, и у панели, а
 * клавиши — только там, где они нарисованы.
 */
export function objectModelChannels(model, channels) {
  const keyed = model && MODELS_KEYED[model.key];
  if (!keyed) return model;
  const want = Math.max(1, Math.min(Math.round(Number(channels) || 1), keyed.max));
  if (want === keyed.keys) return model;
  return { key: model.key, parts: keyed.build(want), keys: want };
}

// ——— висячий вариант тела (таск 256, G397) ————————————————————————————————
//
// Слова заказчика: «Люстре добавь другой вариант - висячая… и что бы
// переключалось как и у тех же дверей опция Стеклянные».
//
// **Устроено как число каналов, а не как второе изображение.** У метки есть
// отметка (`mark.hanging`, правило — `markHangingCan` в `model.js`), и она
// подменяет **модель**, оставляя изображение, габарит и знак на плане теми же,
// — ровно так же, как `objectModelChannels` подменяет клавишную модель по
// числу каналов типа. Своё изображение завести было нельзя: имя изображения
// живёт у **типа** (ADR 005), а висячая люстра — свойство одной метки, и
// типом её не разведёшь, не разведя заодно легенду, таблицы и развёртку.
//
// Пары «обычная → висячая» объявлены там, где лежат оба описания
// (`MODELS_LIGHT_HANGING` в `light.js`). Здесь — только две двери к ним.
const MODELS_HANGING = { ...MODELS_LIGHT_HANGING };

/**
 * Имена изображений, у которых висячий вариант есть. Единственный ответ на
 * «кому предлагать отметку»: своего списка кодов или имён в модели и в панели
 * не заводится — разойдись он с этим, отметка предлагалась бы там, где её
 * некуда применить.
 */
export function objectModelHangingKeys() {
  return Object.keys(MODELS_HANGING);
}

/**
 * **Висячий вариант модели.** Модель, у которой варианта нет, и модель с
 * неснятой отметкой проходят насквозь **той же ссылкой** — как у клавиш: общее
 * описание остаётся общим, и кадр метки без отметки совпадает грань в грань с
 * тем, что он рисовал до этой правки (G68).
 */
export function objectModelHanging(model, hanging) {
  const key = model && hanging === true ? MODELS_HANGING[model.key] : null;
  const other = key ? objectModelByKey(key) : null;
  return other || model;
}

/**
 * **Повтор вдоль пути** по коду типа — то, чем линейная метка отличается от
 * полосы (таск 177, G275). `null` — у этого кода повтора нет, и метка остаётся
 * полосой: так рисуется лента, и так рисовались до этого все линейные типы.
 *
 * Отдельная дверь, а не ступень общей лестницы, потому что и ключ здесь
 * другой: у точечной вещи ключ — имя изображения, у линейной — **код типа**
 * (почему так, разобрано в `lines.js`). Складывать два разных ключа в один
 * справочник значило бы разрешить коду типа занять имя изображения.
 */
export function objectLineModel(code) {
  const key = String(code || "").trim();
  const found = key === "" ? null : MODELS_LINES[key];
  return found ? { key, ...found } : null;
}

/** Все коды с повтором — для сверки пределов тел и граней. */
export function objectLineModelCodes() {
  return Object.keys(MODELS_LINES);
}

/**
 * Модель вещи чертежа по **имени прежнего вида** — мост для уже размеченных
 * объектов (G68).
 *
 * Имя в ключ переводит каталог, терпимо (регистр, «ё», пробелы по краям,
 * корень внутри строки): «Шкаф», «шкафы» и «Шкаф в прихожей» узнаются все, а
 * переименованный в «Пенал» — никто, и тогда вещь честно рисуется габаритом,
 * как рисовалась до моделей.
 */
export function objectModelForName(name) {
  return objectModelByKey(objectCatalogKeyByName(name));
}
