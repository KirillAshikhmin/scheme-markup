// Реестр **низкополигональных моделей** (таск 155, требование G221): один
// плоский справочник «ключ → список тел» и две лестницы, которыми модель
// находят.
//
// ——— откуда у метки модель ———
//
// **По имени её изображения, и третьего механизма не заводится.** Лестница у
// цвета, формы и изображения уже выстроена (ADR 005, `objectViews/registry.js`):
// имя у типа старше формы знака, форма — старше ничего. Модель садится на её
// последнюю ступень: нашлось изображение — его имя и есть ключ модели.
//
// Это даёт сразу три вещи. **Полный охват без единого нового поля:** у всех
// сорока девяти типов стартового справочника изображение есть (это держит
// `test/objectViews.test.js`), значит есть и модель. **Объект заказчика
// оживает без миграции:** в его 592 метках имён изображений нет ни одного, но
// форма знака проставлена, и модель находится по ней — ровно так же, как
// нашлось изображение (G68, объект не меняется). **Одна цена вместо двух:**
// двенадцать типов света делят форму `circle-cross`, и у них одно изображение
// и одна модель — цена, объявленная ещё в таске 135, второй раз не платится.
//
// ——— откуда у вещи чертежа модель ———
//
// По ключу встроенного каталога (таск 154), а у вещи прежней разметки ключа
// нет — там он выводится из имени вида, и переводит имя в ключ сам каталог
// (`objectCatalogKeyByName`), а не второй список слов здесь.
import { objectCatalogKeyByName } from "../objectCatalog.js";
import { MODELS_CLIMATE } from "./climate.js";
import { MODELS_LINES } from "./lines.js";
import { MODELS_LIGHT } from "./light.js";
import { MODELS_NET } from "./net.js";
import { MODELS_OBJECTS } from "./objects.js";
import { MODELS_KEYED, MODELS_POWER } from "./power.js";
import { MODELS_SENSE } from "./sense.js";
import { MODELS_THINGS } from "./things.js";
import { MODEL_CYL_SIDES } from "./kit.js";

/**
 * Предел тел на вещь. Пять — и это посчитанный предел, а не круглое число:
 * тело коробкой стоит шесть граней, цилиндром — десять, сцена живого объекта
 * заказчика держится на тысяче с небольшим граней, а меток на схеме у него под
 * три сотни. Пять тел на каждую — это уже вдвое больше сцены, чем вся
 * квартира; шесть читались бы не лучше, а кадр подорожал бы ещё на пятую
 * часть. Держит это тест, а не уговор.
 */
export const OBJECT_MODEL_BODY_MAX = 5;

/** Предел граней на вещь: пять цилиндров прошли бы по телам, но не по граням. */
export const OBJECT_MODEL_FACE_MAX = 30;

const MODEL_FAMILIES = [
  MODELS_POWER,
  MODELS_LIGHT,
  MODELS_CLIMATE,
  MODELS_SENSE,
  MODELS_NET,
  MODELS_THINGS,
  MODELS_OBJECTS,
];

const MODELS = {};
const CLASHES = [];
for (const family of MODEL_FAMILIES) {
  for (const [key, parts] of Object.entries(family)) {
    // Два семейства, занявшие один ключ, иначе молча затёрли бы друг друга —
    // и у половины типов модель оказалась бы чужой. Список пустой держит тест.
    if (MODELS[key]) CLASHES.push(key);
    MODELS[key] = { key, parts };
  }
}

/** Модель по ключу. `null` — такого ключа нет, и вещь рисуется габаритом. */
export function objectModelByKey(key) {
  return key && MODELS[key] ? MODELS[key] : null;
}

/** Все ключи — для сверки охвата и различимости силуэтов. */
export function objectModelKeys() {
  return Object.keys(MODELS).sort();
}

/** Ключи, занятые дважды. Пусто — иначе тест красный. */
export function objectModelClashes() {
  return [...CLASHES];
}

/**
 * Сколько граней стоит модель: коробка — шесть, цилиндр — своих сторон плюс
 * две. Лежачий цилиндр (таск 177) стоит ровно столько же, сколько стоячий:
 * бока и два днища, — поэтому новый вид тела предела не сдвинул.
 */
export function objectModelFaceCount(model) {
  let faces = 0;
  for (const part of (model && model.parts) || []) {
    faces += part.kind === "cyl" || part.kind === "tube" ? MODEL_CYL_SIDES + 2 : 6;
  }
  return faces;
}

/**
 * Модель с клавишами **по числу каналов типа** (таск 177, G274).
 *
 * Клавишных моделей три с половиной — выключатель на одну, две, три клавиши и
 * переключатель, — а каналов у типа бывает и четыре: «ПП» из стартового
 * справочника двухканальный, а изображение у него переключателя с одной
 * клавишей, и до этого таска он так и стоял на стене одноклавишным. Поэтому
 * число клавиш берётся не из записи реестра, а у типа.
 *
 * Модель, у которой клавиш и так столько, сколько надо, отдаётся **той же
 * ссылкой**: общее описание остаётся общим, и тесты, сверяющие его по ссылке,
 * видят ровно то, что видели.
 *
 * Неклавишная модель проходит насквозь: каналы бывают и у реле, и у панели, а
 * клавиши — только там, где они нарисованы.
 */
export function objectModelChannels(model, channels) {
  const keyed = model && MODELS_KEYED[model.key];
  if (!keyed) return model;
  const want = Math.max(1, Math.min(Math.round(Number(channels) || 1), keyed.max));
  if (want === keyed.keys) return model;
  return { key: model.key, parts: keyed.build(want), keys: want };
}

/**
 * **Повтор вдоль пути** по коду типа — то, чем линейная метка отличается от
 * полосы (таск 177, G275). `null` — у этого кода повтора нет, и метка остаётся
 * полосой: так рисуется лента, и так рисовались до этого все линейные типы.
 *
 * Отдельная дверь, а не ступень общей лестницы, потому что и ключ здесь
 * другой: у точечной вещи ключ — имя изображения, у линейной — **код типа**
 * (почему так, разобрано в `lines.js`). Складывать два разных ключа в один
 * справочник значило бы разрешить коду типа занять имя изображения.
 */
export function objectLineModel(code) {
  const key = String(code || "").trim();
  const found = key === "" ? null : MODELS_LINES[key];
  return found ? { key, ...found } : null;
}

/** Все коды с повтором — для сверки пределов тел и граней. */
export function objectLineModelCodes() {
  return Object.keys(MODELS_LINES);
}

/**
 * Модель вещи чертежа по **имени прежнего вида** — мост для уже размеченных
 * объектов (G68).
 *
 * Имя в ключ переводит каталог, терпимо (регистр, «ё», пробелы по краям,
 * корень внутри строки): «Шкаф», «шкафы» и «Шкаф в прихожей» узнаются все, а
 * переименованный в «Пенал» — никто, и тогда вещь честно рисуется габаритом,
 * как рисовалась до моделей.
 */
export function objectModelForName(name) {
  return objectModelByKey(objectCatalogKeyByName(name));
}
