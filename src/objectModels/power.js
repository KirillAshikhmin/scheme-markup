// Модели меток: розетки, выключатели, розетка данных, щит.
//
// ——— правило, по которому сложены все семьи ———
//
// **Тела не делят плоскостей.** Каждое занимает свой слой по глубине: первое
// начинается на лице габарита (`y: -0.5`), следующее — там, где кончилось
// предыдущее. Два тела с совпавшими лицами порядок граней решал бы жребием
// (коплоскостные грани дерево разбиения кладёт в один узел), и на кадре это
// выглядело бы мерцанием. Поэтому розетка — это сердцевина впереди и рамка за
// ней, а не рамка с сердцевиной на ней.
//
// **Корпус — цветом категории** (`body`), работающая часть — светлее, темнее
// или нейтральная. Так цвет категории остаётся тем, чем он был до моделей:
// пятном, по которому вещь узнают издали (ADR 005). Собери модель наоборот — и
// стена станет бледной, а категории перестанут читаться.
import { modelBox, modelCyl, modelKeys, modelParts } from "./kit.js";

export const MODELS_POWER = {
  // Розетка: керамическая сердцевина впереди, рамка за ней.
  socket: modelParts(
    modelCyl("core", { x: -0.31, width: 0.62, y: -0.5, depth: 0.35, z: 0.19, height: 0.62, material: "light" }),
    modelBox("frame", { y: -0.15, depth: 0.65 }),
  ),
  // Розетка 380: та же пара, но сердцевина крупнее и выходит дальше — силовая
  // колодка и правда толще бытовой, а на кадре это единственное, чем они
  // отличаются телом.
  socket380: modelParts(
    modelCyl("core", { x: -0.39, width: 0.78, y: -0.5, depth: 0.45, z: 0.11, height: 0.78, material: "light" }),
    modelBox("frame", { y: -0.05, depth: 0.55 }),
  ),
  // Выключатели: клавиш столько, сколько каналов. Это единственная разница
  // между «В», «ВВ» и «ВВВ» на стене — и на плоском изображении тоже она.
  switch1: modelParts(modelKeys(1, -0.5, 0.4), modelBox("frame", { y: -0.1, depth: 0.6 })),
  switch2: modelParts(modelKeys(2, -0.5, 0.4), modelBox("frame", { y: -0.1, depth: 0.6 })),
  switch3: modelParts(modelKeys(3, -0.5, 0.4), modelBox("frame", { y: -0.1, depth: 0.6 })),
  // Переключатель: та же одна клавиша, но с качалкой поперёк — она и
  // отличает его от выключателя, когда смотришь в лицо.
  switchToggle: modelParts(
    modelBox("lever", { x: -0.11, width: 0.22, y: -0.5, depth: 0.25, z: 0.36, height: 0.28, material: "dark" }),
    modelKeys(1, -0.25, 0.2),
    modelBox("frame", { y: -0.05, depth: 0.55 }),
  ),
  // Розетка данных: порт прямоугольный и утоплен — по этому и отличается от
  // силовой с круглой сердцевиной.
  data: modelParts(
    modelBox("port", { x: -0.18, width: 0.36, y: -0.5, depth: 0.38, z: 0.3, height: 0.42, material: "dark" }),
    modelBox("frame", { y: -0.12, depth: 0.62 }),
  ),
  // Щит: ящик, дверца и ручка. Автоматов внутри нет нарочно — они за дверцей,
  // и ни одна их грань в кадр не попадёт, а стоить он будет как настоящие.
  panelBox: modelParts(
    modelBox("latch", { x: 0.3, width: 0.12, y: -0.5, depth: 0.2, z: 0.42, height: 0.16, material: "metal" }),
    modelBox("door", { y: -0.3, depth: 0.25, material: "light" }),
    modelBox("case", { y: -0.05, depth: 0.55 }),
  ),
};
