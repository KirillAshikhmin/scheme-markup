// Модели меток: розетки, выключатели, розетка данных, щит.
//
// ——— правило, по которому сложены все семьи ———
//
// **Тела не делят плоскостей.** Каждое занимает свой слой по глубине: первое
// начинается на лице габарита (`y: -0.5`), следующее — там, где кончилось
// предыдущее. Два тела с совпавшими лицами порядок граней решал бы жребием
// (коплоскостные грани дерево разбиения кладёт в один узел), и на кадре это
// выглядело бы мерцанием. Поэтому розетка — это перемычка, гнёзда и круг
// впереди и рамка за ними, а не рамка с кругом на ней.
//
// **Корпус — цветом категории** (`body`), работающая часть — светлее, темнее
// или нейтральная. Так цвет категории остаётся тем, чем он был до моделей:
// пятном, по которому вещь узнают издали (ADR 005). Собери модель наоборот — и
// стена станет бледной, а категории перестанут читаться.
import { modelBox, modelKeys, modelParts, modelTube } from "./kit.js";

// ——— евро-розетка с заземлением (таск 15 сценариев, G18) —————————————————
//
// Слова заказчика (2026-10-23): «а почему розетки выглядт не как розетки, а как
// выключатели? поправь им модель, должна быть классическая евро-розетка с
// заземлением».
//
// **Почему розетка была выключателем.** С таска 155 её сердцевина была
// `modelCyl` — **стоячим** цилиндром: он выдавливается вверх, и круг у него
// лежит в плане, а не на лице. В лицо такой цилиндр — прямоугольник, и розетка
// на стене была светлым квадратом в рамке, то есть одноклавишным выключателем
// прежней раскладки. Таск 14 этого не ломал — его раскладка клавиш розетку не
// трогает, — но до него поверх модели по умолчанию лежал контур изображения
// (круг с гнёздами), и квадрат за ним не читался. Опция «Подсвечивать метки»
// выключилась — и квадрат остался один.
//
// Теперь круг — **лежачий** цилиндр с осью из лица в стену (`modelTube`, ось
// `y`): лицом он круг, как круглое зеркало (таск 177).
//
// ——— как уложить её в четыре тела ———
//
// В евро-розетке шесть видимых вещей: рамка, круглое углубление, два гнезда и
// два заземляющих контакта. Тело на каждую — это 6 + 10 + 4 × 6 = 40 граней при
// пределе тридцать (`OBJECT_MODEL_FACE_MAX`), и даже без одного контакта выходит
// 34. Поэтому два тела здесь работают **парами**:
//
// - **Гнёзда** — одна тёмная планка поперёк круга.
// - **Перемычка** — светлая планка поперёк неё, впереди всех: посередине она
//   закрывает тёмную планку, и та распадается на два гнезда. Цвет у перемычки
//   тот же, что у круга, и лицо у неё смотрит туда же — значит, над кругом её
//   не видно вовсе (у граней одного цвета и одного направления один цвет в
//   кадре). А концы перемычки выходят за круг сверху и снизу — это и есть
//   заземляющие контакты, ровно там, где у евро-розетки скобы.
//
// Контакты поэтому цвета углубления, а не металла: металлический язычок
// требовал бы пятого тела, и розетка не прошла бы предел. На стене это читается
// так же — круг с язычками сверху и снизу и два гнезда.
//
// Углубление на лице не утоплено, а чуть выступает: вычитать тела описание не
// умеет (вещь складывается из кубиков и цилиндров, см. `kit.js`), и «утоплен»
// здесь значит то же, что у порта розетки данных, — другой цвет на том же
// месте. Выступ — миллиметр, чтобы сбоку круг не стал шайбой.
//
// Доли — те же, что у изображения розетки (`objectViews/power.js`): круг 0,3 от
// середины, гнёзда на ±0,12 размером 0,11. Контур изображения поверх модели
// («Подсвечивать метки») ложится на круг и гнёзда, а не мимо них. Скобы у
// изображения нарисованы по бокам круга, у модели контакты — сверху и снизу,
// как у настоящей евро-розетки и как сказано в задании; изображение (лист
// развёртки) этим таском не тронуто.
//
// Тела, как всегда, не делят плоскостей: перемычка, гнёзда, круг и рамка идут
// слоями от лица вглубь, каждое начинается там, где кончилось предыдущее.

/**
 * Евро-розетка: `radius` — круг от середины лица, `pin` — середина гнезда от
 * оси, `hole` — сторона гнезда, `reach` — докуда от середины тянутся
 * контакты; `layers` — толщины перемычки, гнёзд и круга в долях выступа.
 *
 * Ширина перемычки не задаётся, а выводится: она ровно промежуток между
 * гнёздами. Шире — съела бы край гнезда, уже — между гнёздами осталась бы
 * тёмная нить, и два гнезда снова слились бы в щель.
 */
function socketParts({ radius, pin, hole, reach, layers }) {
  const [bridgeDepth, pinsDepth, recessDepth] = layers;
  const bridge = pin * 2 - hole;
  const pinsAt = -0.5 + bridgeDepth;
  const recessAt = pinsAt + pinsDepth;
  const frameAt = recessAt + recessDepth;
  return modelParts(
    // Перемычка между гнёздами; её концы над и под кругом — контакты.
    modelBox("earth", {
      x: -bridge / 2,
      width: bridge,
      y: -0.5,
      depth: bridgeDepth,
      z: 0.5 - reach,
      height: reach * 2,
      material: "light",
    }),
    // Гнёзда: одна планка, которую перемычка делит надвое.
    modelBox("pins", {
      x: -pin - hole / 2,
      width: (pin + hole / 2) * 2,
      y: pinsAt,
      depth: pinsDepth,
      z: 0.5 - hole / 2,
      height: hole,
      material: "dark",
    }),
    // Круглое углубление: лежачий цилиндр, круг — на лице.
    modelTube("recess", {
      axis: "y",
      x: -radius,
      width: radius * 2,
      y: recessAt,
      depth: recessDepth,
      z: 0.5 - radius,
      height: radius * 2,
      material: "light",
    }),
    modelBox("frame", { y: frameAt, depth: 0.5 - frameAt }),
  );
}

// ——— клавиши по числу каналов (таск 177, G274) ————————————————————————————
//
// Слова заказчика: «В объёме Многоканальные выключатели (многоклавишные) рисуй
// так же с несколькими вертикальными клавишами, и обрабатывай клик на каждый
// канал отдельно».
//
// Клавиш у метки столько, сколько каналов **у её типа** (`type.channels`), а не
// сколько их в записи реестра: в реестре имя изображения, и по нему приходит
// одно из трёх описаний, а каналов у типа может быть и четыре. Поэтому
// описание собирается **функцией**, а реестр хранит то, что она даёт на один,
// два и три канала, — и ключ по-прежнему один на изображение и на модель.
//
// Потолок — **четыре клавиши**: четыре плюс рамка и есть пять тел, предел
// таска 155. Это не случайное совпадение с жизнью: четырёхклавишные рамки
// существуют, а то, у чего каналов шесть или двадцать, клавишами не бывает —
// словарь сам говорит, что канал это «клавиша у выключателя, выход у реле,
// кнопка у панели», и рисовать двадцать выходов реле полосками на лице было бы
// враньём. У такого типа клавиш остаётся четыре, и выбрать щелчком можно
// только их; остальные каналы живут в связях, панели и таблице, как и жили.
const MODEL_SWITCH_KEYS_MAX = 4;

const switchParts = (count) => modelParts(modelKeys(count, -0.5, 0.4), modelBox("frame", { y: -0.1, depth: 0.6 }));

const toggleParts = (count) =>
  modelParts(
    modelBox("lever", { x: -0.11, width: 0.22, y: -0.5, depth: 0.25, z: 0.36, height: 0.28, material: "dark" }),
    modelKeys(count, -0.25, 0.2),
    modelBox("frame", { y: -0.05, depth: 0.55 }),
  );

