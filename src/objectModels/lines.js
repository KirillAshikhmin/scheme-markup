// **Повтор вдоль пути** — то, чем линейная метка отличается от полосы
// (таск 177, требование G275).
//
// Слова заказчика: «Трек (трековый светильник) изобрази не просто как полосу, а
// как полосу из которой торчат цилиндры — отдельные точечные светильники. Иначе
// это путается просто с лентой».
//
// ——— почему это не обычная модель ———
//
// Моделей у линейных меток нет и быть не может — так решено в таске 155: «у
// звена нет ни лица, ни верха». И это по-прежнему верно: лента идёт по потолку
// и по стене, гнётся на изломах, у неё нет ни переда, ни верха, ни единого
// габарита, в долях которого описывалось бы тело. Поставить модель на звено
// значило бы выстроить в ряд по люстре на каждый отрезок.
//
// Но у трека есть то, чего у ленты нет: **он состоит из отдельных вещей**.
// Поэтому здесь описывается не модель метки, а **один повторяющийся элемент** и
// правило, с каким шагом он садится на путь. Полоса при этом остаётся полосой —
// её по-прежнему рисуют звенья (`volumePathPrisms`), и лента от этого не
// меняется ни одной гранью.
//
// Вторым этим же механизмом живут **шторы** (G261): в объекте заказчика «Карниз
// штор» — линейный тип (карниз он провёл по окну линией), и модели у него нет
// по той же причине. Полотнища ткани до пола — такой же повтор вдоль пути, как
// светильники трека, только элемент мерится шагом, а не поперечником.
//
// ——— чем находится ———
//
// **По коду типа**, и другого пути у линейной метки нет. У точечной лестница
// изображения идёт «имя у типа → форма знака» (ADR 005), а у линейной знак —
// это **начертание**: у трека он двойная линия, у ленты сплошная. Начертание
// категорийное, у объекта заказчика его нет вовсе (эта возможность появилась
// позже его разметки), и формы знака у линейных типов — общая категорийная,
// одна на все пять. То есть ни один из двух привычных ключей трек от ленты не
// отличает — ни в новом объекте, ни в старом.
//
// Код отличает: «ТР» — это трек и в стартовом справочнике, и в объекте
// заказчика, откуда справочник и приехал. Мост по коду в сборке уже есть и
// заведён ровно для этого — `fillTypeSizes` (G192) подтягивает умолчания
// размеров «по коду и по форме знака». Здесь тот же мост и та же цена:
// переименовал человек код — светильники пропадут, останется полоса. Это
// честнее, чем гадать по толщине.
//
// ——— шаг повтора ———
//
// Шаг — **600 мм**, и это число из жизни: светильники на треке ставят через
// полметра-метр, реже — плотнее у рабочей зоны. Но шаг не кладётся на путь
// жёстко, иначе у трека в 1,7 м последний светильник повис бы в тридцати
// сантиметрах от конца. Поэтому считается **число** светильников —
// `round(длина / шаг)`, не меньше одного, — и они расставляются равномерно с
// отступом полушага от концов (`volumeLineSpots`). Трек в 1,7 м получает три
// светильника через 567 мм, трек в 40 см — один посередине: **на коротком
// отрезке остаётся ровно одна вещь**, и это и есть ответ «чем он не лента».
//
// Потолок — десять светильников на метку. Не для красоты: каждый стоит десять
// граней, и десятка — это сто граней на одну метку, больше, чем вся прежняя
// сцена одной комнаты. Трек длиннее шести метров (а таких в квартире не
// бывает) растянет шаг, а не утопит кадр.
