// Кирпичи, из которых сложены **низкополигональные модели** вещей чертежа и
// меток (таск 155, требование G221).
//
// Слова заказчика: «У этих объектов, а так же у меток в 3д режиме должны быть
// низкополигональные модели для наглядного отображения… бассейн, как пример
// объекта, который уходит под пол можно рисовать просто прямоугольником на
// полу, ну и подобные допущения можно». И решение, из чего их складывать, —
// его же: **из кубиков и цилиндров** в долях габарита; «кровать — матрас плюс
// спинка, унитаз — чаша плюс бачок, бассейн — прямоугольник на полу».
//
// ——— почему те же доли и то же описание данными ———
//
// Это продолжение таска 139: плоские изображения объектов там переведены из
// функций рисования в **список записей** (`objectViews/kit.js`), и объёму
// хватило тех же пяти примитивов, ни одной записи не пришлось переписывать.
// Модель устроена так же и по той же причине: список тел, которые ничего не
// рисуют, а только говорят, из чего вещь состоит. Рисует их один проход в
// `volume.js` — второго места, где разбирается описание, нет.
//
// Видов тела **три**: коробка, стоячий цилиндр и лежачий. Два первых — с
// таска 155, третий добавлен в таске 177 словами заказчика: «Почему у
// стиральной машины перед ней цилиндр вертикальный, хотя логичнее его сделать
// как барабан — горизонтальный и внутри» (G262). Горизонтальной оси у стоячего
// цилиндра нет и быть не может — он выдавливается вверх, — а коробка вместо
// барабана была бы ровно той подменой, на которую заказчик и указал. Поэтому
// вид добавлен, а не вещь упрощена.
//
// Дальше набор не растёт: сфера, конус и кривая по-прежнему лечатся упрощением
// вещи. У «низкополигонально» это не ограничение, а само задание.
//
// ——— система долей ———
//
// У модели своя система координат, привязанная к **лицу** вещи:
//
//   `x` — поперёк лица, −0.5…0.5. Плюс — вправо, если смотреть вещи в лицо;
//         та же сторона, что `x` у плоского изображения, и это нарочно: часть
//         модели и часть рисунка с одной долей оказываются на одной стороне.
//   `y` — в глубину, −0.5 (лицо) … 0.5 (задник).
//   `z` — **вверх от низа габарита**, 0…1. Снизу вверх, а не как `y` у
//         холста: у модели низ есть всегда (матрас над каркасом, бачок над
//         чашей), и мерить его от верха значило бы переворачивать каждую
//         запись в голове.
//
// Тело задаётся углом и размерами — как `viewRect` у изображений, а не
// серединой и половинами: так его границы читаются глазами, не считая в уме.
// Углы по умолчанию дают тело во весь габарит.
//
// ——— цвет ———
//
// Своего цвета у тела **нет**, и это решение, а не недоделка. Цвет
// принадлежит категории (ADR 005), и модель, принеси она свою краску, стала бы
// вторым хозяином цвета: перекрасил человек категорию — а шкаф-то остался
// синим. Поэтому тело называет **материал** из пяти, и все пять считаются от
// цвета самой вещи: `body` — её цвет, разбавленный белым (ровно тот, которым
// рисуется вещь без модели), `light` — светлее, `dark` — темнее того же цвета,
// `metal` и `glass` — почти нейтральные, но с её же оттенком. Считает их
// `volume.js`, и там же они проверяются.
//
// ——— имя и «светится» ———
//
// У каждого тела есть имя и признак `lit`. Это **задел под интерактив**,
// названный заказчиком прямо: метки станут живыми («свет будет включаться,
// датчики реагировать»), и тогда правка должна быть одним полем, а не
// перерисовкой пятидесяти моделей. Сегодня `lit` у всех выключен — это держит
// тест, — а интерпретатор несёт его до тела и там останавливается: включить
// свечение будет одной строкой в одном месте.
//
// Имя — **латинский идентификатор**, не русская подпись. Показывать его пока
// негде, а мёртвый ключ в словаре красит прогон (`test/strings.test.js`): день,
// когда имя части понадобится на экране, добавит строку рядом с остальными.

/** Материалы тела. Все до единого считаются от цвета вещи — см. выше. */
export const MODEL_MATERIALS = ["body", "dark", "light", "metal", "glass"];

/**
 * **Чем тело просвечивает** (таск 189, требование G286). Слова заказчика:
 * «модель штор сделай полупрозрачной, по сути как тюль пусть будет».
 *
 * Признак стоит **у тела**, а не у типа метки, и это главное решение таска.
 * Прозрачна не вся штора, а только ткань: труба карниза над полотнищами
 * остаётся плотной, как и всякая метка. Признак у типа дал бы «прозрачна вся
 * метка» — то есть и трубу, — и к стеклу в дверной раме (таск 180) не подошёл
 * бы вовсе: там прозрачно одно тело из трёх. Поэтому просвечивает **часть
 * модели**, и любая модель может её иметь.
 *
 * Имя, а не число: число — мерка, а мерка повторённая в двух местах есть
 * будущее расхождение. Шторы описаны **дважды** (у точечной метки — моделью в
 * `things.js`, у линейной — повтором в `lines.js`), и положи я в каждую по
 * числу — они бы разошлись первой же правкой. Числа держит `volume.js` рядом с
 * прозрачностью вещей (`VOLUME_CLEAR_ALPHAS`), и что у каждого имени оно есть,
 * проверяет тест.
 *
 * Сегодня имя одно — `sheer`, полотнище шторы. Имя осталось от тюля таска 189,
 * а плотность с таска 191 (G297) — 0,6: ткань стало видно, и это имя **слота**,
 * а не обещание тонкой ткани. Новая плотность (стекло) — это строка здесь и
 * число там, а не второй механизм.
 */
export const MODEL_CLEARS = ["sheer"];

/**
 * Сколько граней у цилиндра. Восемь: на вытянутой руке восьмиугольник читается
 * круглым, а в сцене из тысячи граней каждая вещь стоит денег. Это и есть
 * «низкополигонально» в числе.
 */
export const MODEL_CYL_SIDES = 8;

function modelPart(kind, name, part) {
  const material = MODEL_MATERIALS.includes(part.material) ? part.material : "body";
  return {
    kind,
    name,
    // Выключено у всех и всегда — см. «имя и светится» выше.
    lit: part.lit === true,
    material,
    // **Тело висит до пола** (таск 177, G261). Единственное исключение из долей
    // габарита, и заведено оно под шторы: заказчик сказал «Карниз штор, метку —
    // отрисовывай как шторы на объеме», а габарит у этой метки — сам карниз
    // (400 × 120 × 120 в стартовом справочнике), и полотно в сто двадцать
    // миллиметров шторой не выглядит никак.
    //
    // Поэтому у такого тела верх берётся из долей, как у всех, а низ — ноль,
    // то есть пол помещения. Числа человека при этом не перетолковываются
    // (G68): габарит остаётся габаритом карниза, и выделение, рамка и габарит
    // в колонке считаются по нему. Вниз уходит только рисунок.
    //
    // У лежачего цилиндра признак не действует: растянуть круг до пола значило
    // бы сделать из него овал неизвестной высоты.
    toFloor: part.toFloor === true,
    // **Тело просвечивает** (таск 189, G286): имя плотности из `MODEL_CLEARS`,
    // `null` — плотное, как все. Проверяется по списку, а не берётся как
    // написано: опечатка иначе молча дала бы плотное полотнище, то есть щит на
    // окне вместо тюля.
    clear: MODEL_CLEARS.includes(part.clear) ? part.clear : null,
    x: part.x === undefined ? -0.5 : part.x,
    y: part.y === undefined ? -0.5 : part.y,
    z: part.z === undefined ? 0 : part.z,
    width: part.width === undefined ? 1 : part.width,
    depth: part.depth === undefined ? 1 : part.depth,
    height: part.height === undefined ? 1 : part.height,
  };
}

/** Коробка: угол в долях плюс три размера. Без полей — во весь габарит. */
export function modelBox(name, part = {}) {
  return modelPart("box", name, part);
}

/**
 * Цилиндр: тот же прямоугольник в плане, в него вписан эллипс. Прямоугольник, а
 * не середина с радиусом, — чтобы колонка 150 × 90 осталась овальной, какой она
 * и бывает, и чтобы одно правило читало оба тела.
 */
export function modelCyl(name, part = {}) {
  return modelPart("cyl", name, part);
}

/**
 * **Лежачий цилиндр**: барабан, труба, круглое зеркало — то, у чего ось
 * горизонтальна (таск 177, G262).
 *
 * Прямоугольник тела тот же, что у коробки, а круг вписывается в те две его
 * стороны, что **поперёк оси**: при `axis: "y"` (ось из лица в глубину — так
 * лежит барабан машины и так висит круглое зеркало) кругом становится лицо,
 * вписанное в ширину и высоту; при `axis: "x"` (ось поперёк лица) — бок.
 *
 * По умолчанию круг вписан в доли, и отсюда следствие: **кругом он остаётся,
 * только если круглы сами доли**. Барабан в габарите 600 × 850 круглый по
 * расчёту, а зеркало в габарите 300 × 60 вышло бы овалом — это то же правило,
 * по которому колонна 150 × 90 остаётся овальной (`modelCyl`).
 *
 * `round: true` снимает эту оговорку: диаметр берётся по **большей** стороне
 * тела в миллиметрах, и круг остаётся кругом в любом габарите — даже если для
 * этого ему придётся выйти из габарита, как выходит полотно шторы (`toFloor`).
 * Заведено это для круглого зеркала: габарит у метки «Подсветка зеркала» — сама
 * подсветка (у заказчика в объекте 300 × 60), а зеркало при ней круглое, и
 * вписать круг в полосу значило бы нарисовать не то, о чём он просил. Числа
 * человека при этом целы (G68): габарит остаётся габаритом подсветки, вниз и
 * вверх уходит только рисунок.
 */
export function modelTube(name, part = {}) {
  return {
    ...modelPart("tube", name, part),
    axis: part.axis === "x" ? "x" : "y",
    round: part.round === true,
  };
}

/** Пластина во весь габарит в плане: `z` и `height` — её ярус. */
export function modelSlab(name, z, height, material) {
  return modelBox(name, { z, height, material });
}

/**
 * Лицевая накладка: во всю ширину и высоту габарита, в глубину — от лица
 * назад. Ею начинается почти каждая настенная вещь: рамка розетки, дверца щита,
 * фасад шкафа.
 */
export function modelFront(name, depth, material) {
  return modelBox(name, { y: -0.5, depth, material });
}

/**
 * Клавиши выключателя: столько, сколько каналов. Разница между «В», «ВВ» и
 * «ВВВ» на стене — это они, и на плоском изображении она ровно такая же
 * (`viewKeys`), поэтому и доли здесь те же.
 *
 * **У каждой клавиши стоит номер её канала** (таск 177, G274). Слова заказчика:
 * «обрабатывай клик на каждый канал отдельно рисуя стрелки только на
 * соответствующий канал» — значит клавиша обязана знать, чья она, и знать это
 * в самом описании: иначе отвечать на щелчок пришлось бы разбором имени тела,
 * то есть вторым правилом рядом с первым.
 *
 * Номер доезжает до грани (`volumeModelFaces`) и останавливается там: что
 * значит «канал выделен», решает окно, а в объект не пишется ничего (G68).
 */
export function modelKeys(count, y, depth) {
  const parts = [];
  const width = 0.62 / count;
  for (let index = 0; index < count; index += 1) {
    parts.push({
      ...modelBox("key" + (index + 1), {
        x: -0.31 + index * width + width * 0.08,
        width: width * 0.84,
        y,
        depth,
        z: 0.14,
        height: 0.72,
        material: "light",
      }),
      channel: index + 1,
    });
  }
  return parts;
}

/** Собрать описание: кирпичи возвращают кто тело, кто список. */
export function modelParts(...items) {
  return items.flat(Infinity).filter(Boolean);
}
