// Разбор жеста над полотном: **что пришло и во что это превращается** (таск
// 162, требование G241).
//
// Слова заказчика: «На виде Схема можно двигать полоно 2 пальцами, а на
// Чертеже нет — приведи управление в один вид, без дублирования кода». Разбор
// колеса с приметами трекпада жил в `canvas.js`, а у мастерской чертежа был
// свой щипок по касаниям — два правила вместо одного, и двухпальцевый скролл
// трекпада листал план, но не чертёж.
//
// Теперь правило одно и лежит здесь. Модуль **чистый**: ни DOM, ни состояния,
// ни рисования — на вход событие колеса или две точки касания, на выход
// «сдвинуть на столько» и «умножить масштаб на столько». Применяют это сами
// поверхности: у плана свой `canvasZoomAt`, у чертежа свой `zoomAt`, у окна
// загрузки плана — прокрутка; сводить их в одну функцию значило бы тащить
// сюда три вида состояния.
//
// Зовут модуль три поверхности: план (`canvas.js`), чертёж
// (`panels/workshop.js`) и окно загрузки плана (`panels/schemes.js`). Своих
// примет ни у одной не остаётся.
//
// **Объём (`panels/volume.js`) сюда не ходит, и это не недоделка.** Там другой
// разбор: колесо отодвигает камеру в обзоре, а палец ходит и вертит головой —
// жест тот же, смысл другой, и сводить их в одно правило значило бы соврать.

// ——— колесо и трекпад ————————————————————————————————————————————————
//
// Приметы ниже выверены с заказчиком и перенесены сюда **как есть** — вместе с
// ценой ошибки, названной в них же.
//
// Браузер шлёт двухпальцевый скролл трекпада теми же событиями, что и колесо
// мыши, а различить их надо: колесом заказчик зумит каждый день, двумя пальцами
// привык листать. Цена ошибки несимметрична — сломанный зум мыши хуже, чем
// неузнанный трекпад, — поэтому «листать» включается только по прямой примете
// трекпада, а всё сомнительное остаётся зумом.
//
// Приметы, по порядку надёжности:
// 1. `ctrlKey` — щипок на трекпаде приходит колесом с поднятым ctrlKey (и это
//    же Ctrl+колесо у мыши). Зум всегда, даже посреди прокрутки.
// 2. Строчный и постраничный режимы (`deltaMode` не ноль) шлёт только колесо.
// 3. Горизонтальная составляющая, дробный шаг или шаг мельче щелчка колеса —
//    трекпад. Щелчок колеса — это ровно 100 (Chrome) или 120 пикселей целым
//    числом и без горизонтали.
// 4. Серия: внутри одного жеста решение не меняется. Палец разгоняется, и к
//    середине маха шаги становятся крупными и целыми — по приметам уже колесо;
//    без серии мах переключался бы на зум на полпути.

// Пауза, после которой события колеса считаются новым жестом.
const GESTURE_STREAK_MS = 220;
// Мельче этого шага щелчка у колеса мыши не бывает.
const GESTURE_NOTCH_PX = 40;

// Мера масштаба у колеса и у щипка разная, и мерить их одинаково нельзя:
// щелчок колеса — это сразу сто пикселей, а щипок сыплет дробными единицами по
// несколько за кадр. Пока мера была общей, щипок выходил вялым: чтобы
// приблизить, пальцы приходилось сводить долго.
//
// Колесу оставлена прежняя мера — заказчика она устраивает: щелчок меняет
// масштаб примерно на четырнадцать процентов. Щипку дана мера почти в семь раз
// крупнее: жест на треть экрана — это около сотни единиц, и на такой мере он
// приближает вдвое с лишним, как в привычных редакторах на Mac.
const GESTURE_WHEEL_RATE = 0.0015;
const GESTURE_PINCH_RATE = 0.01;
// Потолок одного события: полтора раза. Резкий щипок (а иные драйверы шлют его
// одним крупным событием) иначе перескакивал бы половину диапазона рывком —
// а весь диапазон холста это шестьсот крат, и пройти его должно не меньше чем
// за полтора десятка событий.
const GESTURE_ZOOM_STEP_MAX = 1.5;

/**
 * Что делать с событием колеса: `zoom` или `pan`. `streak` — `{kind, time}`
 * предыдущего события или `null`.
 */
export function gestureWheelKind(event, streak) {
  if (event.ctrlKey || event.metaKey) return "zoom";
  if (event.deltaMode !== 0) return "zoom";
  if (streak && streak.kind && event.timeStamp - streak.time <= GESTURE_STREAK_MS) return streak.kind;
  const sideways = event.deltaX !== 0;
  const fractional = !Number.isInteger(event.deltaY) || !Number.isInteger(event.deltaX);
  const small = Math.abs(event.deltaY) < GESTURE_NOTCH_PX;
  return sideways || fractional || small ? "pan" : "zoom";
}

/**
 * Щипок на трекпаде: колесо с ctrlKey и мелким или дробным шагом. Ctrl с
 * колесом мыши шлёт те же ровные сто пикселей — у него своя мера, и разгонять
 * его нельзя.
 */
export function gestureWheelPinch(event) {
  if (!event.ctrlKey || event.deltaMode !== 0) return false;
  return !Number.isInteger(event.deltaY) || Math.abs(event.deltaY) < GESTURE_NOTCH_PX;
}

/**
 * Во сколько раз событие меняет масштаб. Шаг пропорционален величине жеста:
 * пальцы двигают масштаб ровно настолько, насколько их свели.
 */
export function gestureZoomFactor(event, pinch) {
  const step = event.deltaMode === 1 ? event.deltaY * 16 : event.deltaY;
  const factor = Math.exp(-step * (pinch ? GESTURE_PINCH_RATE : GESTURE_WHEEL_RATE));
  return Math.min(GESTURE_ZOOM_STEP_MAX, Math.max(1 / GESTURE_ZOOM_STEP_MAX, factor));
}

/**
 * **Единственная дверь для колеса.** Поверхность отдаёт событие и свою память
 * о серии, получает готовый ответ:
 *
 *   `kind`      — `pan` или `zoom`;
 *   `streak`    — что запомнить до следующего события (серия, примета 4);
 *   `panX/panY` — на сколько сдвинуть полотно при `pan`;
 *   `factor`    — во сколько раз изменить масштаб при `zoom`.
 *
 * Оба числа считаются всегда — так ответ читается целиком, а не по ветке.
 *
 * Листаем **как прокрутка**, в ту же сторону, что и стрелки: жест вниз
 * показывает то, что ниже, поэтому содержимое уезжает вверх. Отсюда минусы.
 */
export function gestureWheel(event, streak) {
  const kind = gestureWheelKind(event, streak);
  return {
    kind,
    streak: { kind, time: event.timeStamp },
    panX: -event.deltaX,
    panY: -event.deltaY,
    factor: gestureZoomFactor(event, gestureWheelPinch(event)),
  };
}

// ——— касания ——————————————————————————————————————————————————————————
//
// Щипок двумя пальцами на планшете. Примет здесь не нужно: два пальца — это
// всегда щипок, и мера у него прямая (во сколько раз развели — во столько и
// приблизили), без `GESTURE_PINCH_RATE`: разгонять то, что человек ведёт
// руками, незачем.
//
// **Порядок применения** у всех поверхностей один, и взят он с плана, потому
// что к нему заказчик привык: сперва масштаб вокруг новой середины между
// пальцами, потом сдвиг на то, насколько эта середина уехала. Пальцы
// одновременно сводят и везут — и то и другое должно случиться за один шаг.

/** Щипок по двум точкам: расстояние и середина. Точек не две — `null`. */
export function gesturePinchOf(points) {
  const [first, second] = [...points];
  if (!first || !second) return null;
  return {
    distance: Math.hypot(first.x - second.x, first.y - second.y),
    center: { x: (first.x + second.x) / 2, y: (first.y + second.y) / 2 },
  };
}

/**
 * Шаг щипка: от прошлого состояния к новым точкам.
 *
 * Возвращает `{factor, panX, panY, pinch}` — множитель масштаба, ход середины
 * и что запомнить до следующего события. `factor` ровно 1, пока мерить не от
 * чего: нулевое расстояние (пальцы пришли в одну точку) не должно уносить
 * масштаб в бесконечность.
 */
export function gesturePinchStep(previous, points) {
  const now = gesturePinchOf(points);
  if (!now) return null;
  const was = previous || now;
  const factor = was.distance > 0 && now.distance > 0 ? now.distance / was.distance : 1;
  return {
    factor,
    panX: now.center.x - was.center.x,
    panY: now.center.y - was.center.y,
    pinch: now,
  };
}
