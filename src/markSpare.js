// Запасной габарит: **одна новость на все поверхности** (G226, G230).
//
// Слова заказчика: «да, и на развёртке тоже пиши про додуманную сторону».
//
// ——— почему это живёт отдельным местом ———————————————————————————————————
//
// Правило габарита сведено в `markBox.js`: сторона, которой у типа нет,
// берётся у габарита изображения объекта, а без изображения — у общей рамки.
// Догадка эта честная, но догадка, и молчать о ней нельзя: человек решит, что
// числа заданы, и станет размечать щит по картинке.
//
// Говорил о ней **только объём** — строкой под полем, — а развёртка молчала,
// хотя считает тот же самый габарит тем же самым `markBoxMm`. Асимметрию
// назвал исполнитель таска 156, заказчик решил её убрать.
//
// Поэтому слова о запасном габарите лежат здесь, рядом с правилом, а не у
// поверхностей: напиши их у каждой — и они разойдутся точно так же, как
// разошлось само правило до таска 156. Поверхность решает **показывать или
// нет**, а не **как сказать**.
//
// ——— одна строка, а не две похожих ————————————————————————————————————————
//
// Строка выверена с заказчиком ещё в объёме и здесь не переписана, а разнята на
// две части по месту, которое у поверхности есть:
//
//   **голова** — факт и кто: «Нарисованы запасным габаритом: 2 — ПЗ1, МВ1».
//     Её говорят все три поверхности, и лист развёртки — тоже: подпись над
//     чертежом вмещает ровно столько;
//   **хвост** — откуда взяты числа и что сделать. Он для того, у кого есть
//     место под абзац: плашка объёма и подпись под полосой развёртки.
//
// Это не два текста об одном: факт сформулирован один раз и объяснение один
// раз. Поставь их врозь по поверхностям — и получились бы те самые две похожие
// строки, которых заказчик просил не писать.
//
// **Про выступ в хвосте не сказано нарочно.** Рамка отвечает и за него
// (`MARK_BOX_FRAME_DEPTH_MM`, 10 мм), но это ответ **объёма**: на листе
// развёртки выступа нет вовсе, и назвать его там значило бы пообещать
// измерение, которого на чертеже не нарисовано. Сам запасной выступ от этого
// никуда не делся — он описан там, где живёт (`volumeMarkPlacement`).
import { MARK_BOX_FRAME_MM } from "./markBox.js";
import { text } from "./strings.js";

/**
 * Сколько имён помещается в перечень под полем, прежде чем пойдёт «и ещё N».
 *
 * Мера **одна на сборку**: и у запасного габарита, и у неразмещённых меток в
 * объёме. Это одна и та же строка под одним и тем же полем, и обрываться она
 * обязана одинаково — поэтому число лежит в одном месте, а не повторено
 * числом 8 в двух файлах.
 */
export const MARK_LIST_SHOWN = 8;

/**
 * Перечень имён, который не выталкивает поле за край окна: `MARK_LIST_SHOWN`
 * названы, дальше «и ещё N». Полный список уходит в подсказку строки.
 */
export function markNamedList(list, name, moreKey) {
  const named = list.slice(0, MARK_LIST_SHOWN).map(name);
  if (list.length > MARK_LIST_SHOWN) {
    named.push(text(moreKey, { count: list.length - MARK_LIST_SHOWN }));
  }
  return named.join(", ");
}

/**
 * Строка о вещах, нарисованных запасным габаритом. Пусто — **пустая строка**:
 * говорить не о чем, и плашки с ней быть не должно. На объекте заказчика таких
 * вещей ноль, и правильный ответ там — тишина, а не пустое предупреждение.
 *
 * `list` — `[{label}]` в порядке таблицы меток. `options.why` — добавить хвост с
 * объяснением: его просят поверхности, у которых есть место под абзац.
 *
 * Чистая и вынесена наружу: строку, собранную в обработчике кадра, не проверяет
 * ничто, а соврать о размере вещи здесь легче всего.
 */
export function markSpareLine(list, options = {}) {
  const named = list || [];
  if (named.length === 0) return "";
  const head = text("spare.line", {
    count: named.length,
    list: markNamedList(named, (item) => item.label, "spare.more"),
  });
  if (options.why !== true) return head;
  return head + ". " + text("spare.why", { side: MARK_BOX_FRAME_MM });
}

/** Все нарисованные запасным габаритом — в подсказку строки, когда их много. */
export function markSpareTitle(list) {
  const named = list || [];
  if (named.length <= MARK_LIST_SHOWN) return "";
  return named.map((item) => item.label).join(", ");
}
