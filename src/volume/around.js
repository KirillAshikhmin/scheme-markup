// «Объём»: обзор со стороны — камера над домом, её мера и предел.
//
// Часть «Объёма», вынесенная из `src/volume.js` (2026-10-25) переносом без
// переименований: снаружи модуль читают через дверь `volume.js`, а соседи по
// `src/volume/` — напрямую. Зависимости идут только вниз по слоям (порядок —
// в шапке `volume.js`), циклов нет. Решения и доводы — в шапках разделов ниже.
import { WALL_HEIGHT_FALLBACK_MM } from "../model.js";
import {
  VOLUME_AROUND_FLY_S,
  VOLUME_AROUND_MAX_MM,
  VOLUME_AROUND_MIN_MM,
  VOLUME_AROUND_NEAR_MM,
  VOLUME_AROUND_TILT_MIN,
  VOLUME_LAYER_MARK,
  VOLUME_MARKER_MM,
  VOLUME_MARKER_RGB,
  VOLUME_WALK_MM_S,
} from "./measures.js";
import { volumeClockwise, volumeFace } from "./faces.js";
import { volumeBasis, volumeFocal } from "./camera.js";
import { volumeGroundMm } from "./walk.js";

// ——— обзор со стороны ————————————————————————————————————————————————————

// ——— предел стояния снят (таск 200, G304) ———————————————————————————————
//
// Таск 195 завёл `volumeAroundStand`: взгляд задирался свободно, а место камеры
// держалось над крышей — ровно затем, чтобы камера не оказалась **внутри**
// стены, где кадр становится серым полем и читается как поломка.
//
// Заказчик этот предел снял сам: «по камере — ок, пусть в стенах оказываемся,
// это ожидаемо». Поэтому **серый кадр внутри стены снова возможен, и это его
// выбор, а не дефект сборки.** Замены пределу нет и заводить её нельзя: ни
// выталкивания камеры из стены, ни гашения ближних граней — обзор получил
// механику полёта (пробел выше, Control ниже, ход по взгляду) и летает сквозь
// стены всегда, потому что камера — не человек.
//
// Что осталось от прежнего устройства: **цель обзора больше не хранится**. У
// обзора хранится место камеры (`eye`), а цель — точка перед ней на
// `distance`, то есть та, в которую она летит. Поэтому «брошенной цели на
// другом конце квартиры» не бывает: вращение крутит точку перед собой, а
// колесо подводит камеру к ней.

/**
 * Где стоит камера, смотрящая на `target` с расстояния `distance`.
 *
 * Этим считают **кадрирование**: «Обзор» ставит камеру на человека, «Вся
 * схема» — на середину чертежа, колесо подводит её к той же цели ближе. Пол
 * держит и здесь (`volumeGroundMm`): задранный взгляд с близкой целью иначе
 * увёл бы камеру под плиту.
 */
export function volumeAroundEye(target, yaw, pitch, distance) {
  const basis = volumeBasis({ yaw, pitch });
  return {
    x: target.x - basis.fwd.x * distance,
    y: target.y - basis.fwd.y * distance,
    z: volumeGroundMm(target.z - basis.fwd.z * distance),
  };
}

/**
 * Цель обзора: точка перед камерой на `distance`. Своей цели обзор не хранит —
 * разбор выше, у `volumeAroundEye`.
 */
export function volumeAroundTarget(eye, yaw, pitch, distance) {
  const basis = volumeBasis({ yaw, pitch });
  return {
    x: eye.x + basis.fwd.x * distance,
    y: eye.y + basis.fwd.y * distance,
    z: eye.z + basis.fwd.z * distance,
  };
}

/** Камера, смотрящая на `target` с расстояния `distance`: место и взгляд. */
export function volumeAroundCamera(target, yaw, pitch, distance) {
  return { at: volumeAroundEye(target, yaw, pitch, distance), yaw, pitch };
}

// ——— одна мера обзора (таск 207, G311 и G312) ————————————————————————————
//
// Слова заказчика: «почему движение мыши с зажатой клавишей перемещает камеру
// вокруг какой-то цели, а не просто поворачивает камеру как при виде от 1
// лица? должно быть так же».
//
// Орбиты больше нет: мышь вертит камеру **на месте**, тем же правилом, что в
// первом лице. Вместе с орбитой ушла и хранимая `distance` — расстояние до
// цели, которую больше никто не обходит. Два смысла у неё оставлять нельзя
// (прямое требование тикета), поэтому смысл один и он **считается, а не
// хранится**: `volumeAroundReach` — докуда обзор достаёт до пола по взгляду.
//
// Этой одной мерой живёт всё, что спрашивало расстояние:
//
//   - **шаг колеса и щипка**: они везут камеру по взгляду на долю меры, то
//     есть приближение больше не упирается в предел и не умирает в комнате;
//   - **свайп двумя пальцами** (`volumeAroundPan`): мера пикселя — `distance /
//     focal`, и с таска 207 это **честная** глубина пола. До него там лежала
//     длина орбитальной руки, которую полёт не трогал: слетев с тридцати
//     метров в комнату, человек возил карту мерой тридцати метров (дефект,
//     заведённый таском 200);
//   - **скорость полёта** (`volumeAroundSpeed`).
//
// Кадрирование («Обзор», «Вся схема») расстоянием по-прежнему **пользуется**,
// но как доводом: поставило место и взгляд — мера посчиталась сама.

/**
 * Докуда обзор достаёт до пола по взгляду — одна мера на приближение, свайп и
 * скорость.
 *
 * Отвесно вниз это высота камеры, наискось — длиннее, в горизонт и вверх пола
 * нет вовсе, и мера берётся по самому пологому взгляду, на котором его ещё
 * считают (`VOLUME_AROUND_TILT_MIN`, тот же предел, что у свайпа). У земли,
 * где до пола ноль, снизу держит `VOLUME_AROUND_MIN_MM`: иначе и колесо, и
 * полёт встали бы намертво ровно там, куда заказчик просил пускать камеру.
 */
export function volumeAroundReach(eye, pitch) {
  const down = Math.max(VOLUME_AROUND_TILT_MIN, -Math.sin(Number(pitch) || 0));
  return volumeAroundDistance((Number(eye && eye.z) || 0) / down);
}

/**
 * Как быстро летит обзор (таск 207, G311): он покрывает то, до чего достаёт,
 * за `VOLUME_AROUND_FLY_S`.
 *
 * **Вблизи точность, издали размах** — и это не две скорости, а одно
 * отношение. Числа на объекте заказчика (квартира 9,8 × 9,9 м):
 *
 *   - «Вся схема» — камера в 18 м над планом, мера 27 м, скорость **18 м/с**:
 *     квартиру пролетает за полсекунды, с Shift — вчетверо быстрее пешехода;
 *   - в комнате на высоте глаз при взгляде чуть вниз мера 4,7 м, скорость
 *     **3,1 м/с** — четверть сверх пешехода, то есть ход, а не рывок;
 *   - у самой земли мера упирается в полтора метра, и скорость была бы
 *     0,9 м/с — медленнее человека. Поэтому снизу её держит **шаг пешехода**:
 *     обзор нигде не ходит медленнее, чем ходит человек.
 *
 * Shift удваивает, как удваивал: бег и полёт — одно и то же движение в разных
 * видах, и второго множителя для обзора не заводится.
 */
export function volumeAroundSpeed(reachMm, run) {
  const want = volumeAroundDistance(reachMm) / VOLUME_AROUND_FLY_S;
  const base = Math.max(VOLUME_WALK_MM_S, want);
  return run ? base * 2 : base;
}

/**
 * Обзор, в котором видно всю схему: цель — середина чертежа, расстояние —
 * такое, чтобы габарит уместился в поле. Окно открывается именно им: заказчик
 * сказал, что показ начинается с общего вида.
 */
export function volumeAroundFit(scene, box) {
  // Габарит в плане: у одной схемы — её чертёж, у стопки этажей — все они
  // вместе (таск 202).
  const bounds = (scene.stackMm && scene.stackMm.boundsMm) || scene.boundsMm;
  // Габарит по вертикали: у одной схемы — её высота от нуля, у стопки этажей
  // (таск 202) — вся она, от пола нижнего этажа до потолка верхнего. Отсчёт
  // идёт от пола открытой схемы, поэтому низ стопки бывает отрицательным, и
  // середина вместе с ним уходит вниз: взять `height / 2` значило бы навести
  // камеру на небо над домом.
  const span = scene.stackMm || { bottomMm: 0, topMm: scene.heightMm || WALL_HEIGHT_FALLBACK_MM };
  const height = Math.max(1, span.topMm - span.bottomMm);
  const middle = (span.topMm + span.bottomMm) / 2;
  if (!bounds) {
    return { target: { x: 0, y: 0, z: middle }, distance: VOLUME_AROUND_NEAR_MM };
  }
  const target = {
    x: (bounds.minX + bounds.maxX) / 2,
    y: (bounds.minY + bounds.maxY) / 2,
    z: middle,
  };
  // Габарит берётся с выносом: стены стоят толщиной за своими осями, пол под
  // ними — с напуском (D37), и всё это обязано попасть в кадр.
  const outset = (scene.outsetMm || 0) * 2;
  const radius = Math.hypot(bounds.widthMm + outset, bounds.heightMm + outset, height) / 2;
  const focal = volumeFocal(box);
  const fit = (radius * focal) / (0.42 * Math.min(box.width, box.height));
  return { target, distance: volumeAroundDistance(fit) };
}

export function volumeAroundDistance(value) {
  return Math.max(VOLUME_AROUND_MIN_MM, Math.min(VOLUME_AROUND_MAX_MM, value));
}

/**
 * Перенос обзора двумя пальцами: ход середины между пальцами — в сдвиг цели по
 * полу, миллиметры (таск 174, требование G256).
 *
 * Слова заказчика: «сделай в объеме на мобильном интерфейсе что бы карта в
 * режиме сверху двигалась 2 пальцами». Сам жест разбирает общий `gestures.js`
 * (`gesturePinchStep` отдаёт и множитель масштаба, и ход середины) — а перевести
 * этот ход в миллиметры может только камера: это её счёт, и он здесь.
 *
 * Тем же ходом возит и двухпальцевый свайп трекпада (таск 195, требование
 * G299): жест разбирает тот же `gestures.js` (`gestureWheel` отдаёт `pan` с
 * готовым ходом в экранных точках), а перевод в миллиметры здесь один на оба
 * устройства.
 *
 * Правило — **пол едет за пальцами**: куда ушла середина, туда уехала карта, а
 * камера на столько же в обратную сторону. Ответ — сдвиг **по полу**, и высота
 * камеры им не меняется: вверх и вниз обзор ходит пробелом и Control (таск
 * 200), а свайп — это «скролл», слово заказчика.
 *
 * Мера одного пикселя — `distance / focal`: ширина пикселя на той глубине, где
 * лежит цель. Отошли дальше — палец возит крупнее, и это ровно то, что видно
 * глазом.
 *
 * Поперёк взгляда счёт точный: камера не кренится, и экранное «вправо» лежит
 * на полу целиком. Вдоль — в сторону взгляда, положенного на пол, и с
 * поправкой на наклон: пол на экране сжат ровно во столько, во сколько короче
 * единицы экранный «верх», положенный на пол (это синус наклона). Без поправки
 * карта отставала бы от пальца вверх-вниз, хотя поперёк шла бы вровень.
 *
 * Сторона берётся у **взгляда**, а не у «верха» (таск 195): у задранного
 * взгляда горизонтальная часть «верха» разворачивается назад, и карта поехала
 * бы от пальца в обратную сторону. На опущенном взгляде — а другого до таска
 * 195 в обзоре не было — обе стороны это одно и то же направление, и числа от
 * замены не изменились ни на бит.
 *
 * Поправка **ограничена** `VOLUME_AROUND_TILT_MIN`: у почти
 * горизонтального взгляда она уходит в бесконечность — пол под пальцем там
 * лежит у горизонта, то есть в километрах, — и один мах уносил бы обзор
 * неизвестно куда. Положе двадцати градусов карта просто отстаёт от пальца, и
 * это по-прежнему управляемо.
 */
export function volumeAroundPan(view, box, panX, panY) {
  const distance = Number(view && view.distance) || 0;
  const focal = box ? volumeFocal(box) : 0;
  if (!(distance > 0) || !(focal > 0)) return { dx: 0, dy: 0 };
  const perPixel = distance / focal;
  const basis = volumeBasis({ yaw: view.yaw, pitch: view.pitch });
  // Взгляд, положенный на пол, — сторона сдвига вдоль. У отвесного взгляда
  // класть нечего (он сам отвесный), и сторону даёт рысканье — то же самое
  // направление в пределе.
  const flat = Math.hypot(basis.fwd.x, basis.fwd.y);
  const forward =
    flat > 1e-9
      ? { x: basis.fwd.x / flat, y: basis.fwd.y / flat }
      : { x: Math.cos(view.yaw || 0), y: Math.sin(view.yaw || 0) };
  // Экранный «верх», положенный на пол: его длина и есть мера сжатия пола
  // (синус наклона). Знака у неё нет — сторону уже дал взгляд.
  const lean = Math.hypot(basis.up.x, basis.up.y);
  const tilt = Math.max(VOLUME_AROUND_TILT_MIN, lean);
  const across = -(Number(panX) || 0) * perPixel;
  const along = ((Number(panY) || 0) * perPixel) / tilt;
  return {
    dx: basis.right.x * across + forward.x * along,
    dy: basis.right.y * across + forward.y * along,
  };
}

/**
 * Где стоит человек — кружок на полу и треугольник взгляда.
 *
 * Заказчик про обзор: «без него не понять, где стоишь». Значит обзор обязан
 * показать не только комнату, но и самого смотрящего — иначе он отвечает на
 * половину вопроса. Кружок лежит чуть выше пола и идёт **последним ярусом**,
 * поверх всего: ближняя стена под углом прячет за собой полосу пола метра в
 * три, и указатель, который она закрывает, бесполезен.
 *
 * Радиус — `VOLUME_MARKER_MM`, и он вдвое меньше прежнего (G212: «Позицию на
 * схеме на обзорном виде сделай меньше»). Кружок в 320 мм на обзоре квартиры
 * закрывал собой полметра пола — то есть ровно то место, куда человек
 * собирался перейти кликом.
 */
export function volumeMarkerFaces(at, yaw, out = [], radiusMm = VOLUME_MARKER_MM) {
  const radius = radiusMm;
  const lift = 15;
  const circle = [];
  const steps = 14;
  for (let index = 0; index < steps; index += 1) {
    const angle = (index / steps) * Math.PI * 2;
    circle.push({ x: at.x + Math.cos(angle) * radius, y: at.y + Math.sin(angle) * radius, z: lift });
  }
  out.push(volumeFace(volumeClockwise(circle).map((point) => ({ ...point, z: lift })), VOLUME_MARKER_RGB, {
    normal: { x: 0, y: 0, z: 1 },
    layer: VOLUME_LAYER_MARK,
  }));
  const tip = { x: at.x + Math.cos(yaw) * radius * 2.4, y: at.y + Math.sin(yaw) * radius * 2.4, z: lift };
  const left = {
    x: at.x + Math.cos(yaw + Math.PI / 2) * radius * 0.62,
    y: at.y + Math.sin(yaw + Math.PI / 2) * radius * 0.62,
    z: lift,
  };
  const right = {
    x: at.x + Math.cos(yaw - Math.PI / 2) * radius * 0.62,
    y: at.y + Math.sin(yaw - Math.PI / 2) * radius * 0.62,
    z: lift,
  };
  out.push(volumeFace(volumeClockwise([tip, left, right]).map((point) => ({ ...point, z: lift })), VOLUME_MARKER_RGB, {
    normal: { x: 0, y: 0, z: 1 },
    layer: VOLUME_LAYER_MARK,
  }));
  return out;
}
