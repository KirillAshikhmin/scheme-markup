/** Есть ли у имени картинка — по этому тест сверяет имена с описаниями. */
export function volumeArtNames() {
  return Object.keys(VOLUME_ARTS).sort();
}

/** Сколько граней стоит картинка: стекло экрана плюс её фигуры. */
export function volumeArtFaceCount(name, lit = false) {
  const art = VOLUME_ARTS[name];
  if (!art) return 0;
  return art.length + (lit ? 1 : 0);
}

/**
 * **Лицо тела в миллиметрах**: `{at, u, normal, widthMm, heightMm}` — середина
 * лица, ось вдоль него, нормаль наружу и две стороны. Лицо тела — его сторона
 * при `y = part.y`: доля `y` у описаний растёт в глубину от лица (`kit.js`),
 * поэтому передняя сторона у коробки всегда эта.
 *
 * `null` — лица нет: у габарита нулевой высоты, у вырожденного тела.
 */
export function volumeArtFace(frame, part) {
  if (!frame || !part || !(frame.heightMm > 0)) return null;
  // **Картинка бывает только у коробки**, и это сказано здесь, а не додумано
  // там: у цилиндра, лежачей трубы и конуса лица нет — есть бок, и плоский
  // прямоугольник на нём повис бы в воздухе. Экран и полотно — коробки.
  if (part.kind !== "box") return null;
  const bottomMm = part.toFloor ? 0 : frame.bottomMm + part.z * frame.heightMm;
  const topMm = frame.bottomMm + (part.z + part.height) * frame.heightMm;
  const widthMm = Math.abs(part.width) * frame.widthMm;
  const heightMm = topMm - bottomMm;
  if (!(widthMm > 0) || !(heightMm > 0)) return null;
  const normal = { x: -frame.f.x, y: -frame.f.y, z: 0 };
  const alongX = part.x + part.width / 2;
  return {
    at: {
      x: frame.at.x + frame.u.x * alongX * frame.widthMm + frame.f.x * part.y * frame.depthMm + normal.x * VOLUME_ART_LIFT_MM,
      y: frame.at.y + frame.u.y * alongX * frame.widthMm + frame.f.y * part.y * frame.depthMm + normal.y * VOLUME_ART_LIFT_MM,
      z: (bottomMm + topMm) / 2,
    },
    u: { x: frame.u.x, y: frame.u.y, z: 0 },
    normal,
    widthMm,
    heightMm,
  };
}

/**
 * Грани картинки на лице тела: стекло под рамкой (только у тела, которое может
 * светиться) и фигуры картинки поверх него.
 *
 * `rgb` — цвет самого тела (материал уже посчитан): стекло считается от него, а
 * фигуры несут свой цвет. `options` — то же, что у граней тела: хозяин
 * (`markId`), плотность (`clear`), канал. Признак `lit` ставится здесь: у
 * стекла да, у фигур нет.
 */
export function volumeArtFaces(frame, part, rgb, out = [], options = {}) {
  const art = VOLUME_ARTS[part && part.art];
  const face = art ? volumeArtFace(frame, part) : null;
  if (!face) return out;
  const screen = part.lit === true;
  // Рамка — само тело вокруг стекла; её мера одна, и сжимается она только там,
  // где стеклу иначе не остаться стеклом.
  const frameMm = Math.min(VOLUME_ART_FRAME_MM, face.widthMm / 4, face.heightMm / 4);
  const glassW = face.widthMm - frameMm * 2;
  const glassH = face.heightMm - frameMm * 2;
  const at = (fx, fy) => ({
    x: face.at.x + face.u.x * fx * glassW,
    y: face.at.y + face.u.y * fx * glassW,
    z: face.at.z + fy * glassH,
  });
  const quad = (points, color, kind, lit) =>
    out.push(
      volumeFace(points.map(([fx, fy]) => at(fx, fy)), color, {
        ...options,
        normal: face.normal,
        art: kind,
        lit,
        led: kind === "screen",
      }),
    );
  if (screen) {
    quad(artRect(-0.5, -0.5, 0.5, 0.5), rgb.map((value) => Math.round(value * VOLUME_ART_GLASS)), "glass", true);
  }
  for (const shape of art) {
    quad(shape.disc ? artDisc(shape.disc, glassW, glassH) : shape.points, shape.rgb, screen ? "screen" : "canvas", false);
  }
  return out;
}

/** Круг картинки: радиус по короткой стороне стекла, чтобы круг остался кругом. */
function artDisc([cx, cy, r], glassW, glassH) {
  const short = Math.min(glassW, glassH);
  const rx = (r * short) / glassW;
  const ry = (r * short) / glassH;
  const points = [];
  for (let side = 0; side < VOLUME_ART_SIDES; side += 1) {
    const angle = ((side + 0.5) * Math.PI * 2) / VOLUME_ART_SIDES;
    points.push([cx + Math.cos(angle) * rx, cy + Math.sin(angle) * ry]);
  }
  return points;
}
